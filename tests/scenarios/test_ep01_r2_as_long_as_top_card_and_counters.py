"""Scenario: conditional statics read live off the top card of a library and
off counters on their own source (EP-01 round 2, task 3).

Mul Daya Channelers ("As long as the top card of your library is a creature
card, this creature gets +3/+3." / "... is a land card, this creature has
'{T}: Add two mana of any one color.'") and Vampire Nocturnus ("As long as the
top card of your library is black, this creature and other Vampire creatures
you control get +2/+1 and have flying.") read the library; the Myojin cycle
("Myojin of Infinite Rage has indestructible as long as it has a divinity
counter on it.") and Zhao ("As long as Zhao has a conqueror counter on him,
nonbasic lands are Mountains.") read counters on their own source.

Verified with `mise run rules:find`:

- CR 611.3a: a continuous effect generated by a static ability "isn't
  'locked in'; it applies at any given moment to whatever its text
  indicates" - so the effect follows the top card as it changes.
- CR 604.2: static abilities create continuous effects active as long as the
  permanent remains on the battlefield and has the ability.
- CR 613.1f: layer 6 adds abilities; CR 613.4c: sublayer 7c modifies power
  and toughness.
- CR 122.1: a counter is a marker placed on an object.
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone
from tests.scenarios.harness import Scenario

MUL_DAYA = "Mul Daya Channelers"
NOCTURNUS = "Vampire Nocturnus"
TWO_MANA = "{T}: Add two mana of any one color."


def _board(
    alice_battlefield: list[str],
    alice_library: list[str],
    *,
    bob_battlefield: list[str] | None = None,
    bob_library: list[str] | None = None,
):
    scenario = (
        Scenario()
        .player("alice", battlefield=alice_battlefield, library=alice_library + ["Island"] * 4)
        .player(
            "bob",
            battlefield=bob_battlefield or ["Mountain"],
            library=(bob_library or []) + ["Mountain"] * 4,
        )
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


def _chars(scenario, name: str, username: str = "alice"):
    return scenario.game.characteristics_of(scenario.find(name, Zone.BATTLEFIELD, username))


# -- Mul Daya Channelers -------------------------------------------------------


def test_top_creature_card_makes_channelers_a_5_5():
    scenario = _board([MUL_DAYA], ["Grizzly Bears"])
    assert _chars(scenario, MUL_DAYA).power_toughness == (5, 5)
    assert scenario.game.continuous_effects.layer_notices == []


def test_top_noncreature_nonland_card_leaves_channelers_a_2_2():
    scenario = _board([MUL_DAYA], ["Lightning Bolt"])
    chars = _chars(scenario, MUL_DAYA)
    assert chars.power_toughness == (2, 2)
    assert TWO_MANA not in chars.abilities


def test_top_land_card_grants_the_two_mana_ability_and_no_pump():
    scenario = _board([MUL_DAYA], ["Forest"])
    chars = _chars(scenario, MUL_DAYA)
    assert chars.power_toughness == (2, 2)
    assert TWO_MANA in chars.abilities


def test_flip_drawing_the_top_card_moves_the_pump_to_the_next_card():
    """CR 611.3a: not locked in. Drawing the creature exposes a land."""
    scenario = _board([MUL_DAYA], ["Grizzly Bears", "Forest"])
    assert _chars(scenario, MUL_DAYA).power_toughness == (5, 5)
    scenario.draw()
    chars = _chars(scenario, MUL_DAYA)
    assert chars.power_toughness == (2, 2)
    assert TWO_MANA in chars.abilities


def test_only_the_controllers_library_is_read():
    scenario = _board([MUL_DAYA], ["Lightning Bolt"], bob_library=["Grizzly Bears"])
    assert _chars(scenario, MUL_DAYA).power_toughness == (2, 2)


def test_other_creatures_are_not_pumped_by_the_channelers_line():
    scenario = _board([MUL_DAYA, "Grizzly Bears"], ["Grizzly Bears"])
    assert _chars(scenario, "Grizzly Bears").power_toughness == (2, 2)


def test_granted_mana_ability_actually_taps_for_two_mana_of_one_color():
    scenario = _board([MUL_DAYA], ["Forest"])
    channelers = scenario.find(MUL_DAYA, Zone.BATTLEFIELD, "alice")
    assert any(ability.raw == TWO_MANA for ability in scenario.game.activated_abilities(channelers))


# -- Vampire Nocturnus ---------------------------------------------------------


def test_top_black_card_pumps_nocturnus_and_other_vampires_and_gives_flying():
    scenario = _board([NOCTURNUS, "Vampire Nighthawk"], ["Gray Merchant of Asphodel"])
    own = _chars(scenario, NOCTURNUS)
    other = _chars(scenario, "Vampire Nighthawk")
    assert own.power_toughness == (5, 4)
    assert "Flying" in own.abilities or any(a.lower() == "flying" for a in own.abilities)
    assert other.power_toughness == (4, 4)


def test_top_nonblack_card_pumps_nobody():
    scenario = _board([NOCTURNUS, "Vampire Nighthawk"], ["Grizzly Bears"])
    assert _chars(scenario, NOCTURNUS).power_toughness == (3, 3)
    assert _chars(scenario, "Vampire Nighthawk").power_toughness == (2, 3)


def test_nonvampire_creatures_are_not_pumped_even_with_a_black_top_card():
    scenario = _board([NOCTURNUS, "Grizzly Bears"], ["Gray Merchant of Asphodel"])
    assert _chars(scenario, "Grizzly Bears").power_toughness == (2, 2)


def test_flip_black_top_card_drawn_ends_the_pump():
    scenario = _board([NOCTURNUS], ["Gray Merchant of Asphodel", "Grizzly Bears"])
    assert _chars(scenario, NOCTURNUS).power_toughness == (5, 4)
    scenario.draw()
    assert _chars(scenario, NOCTURNUS).power_toughness == (3, 3)


# -- counters on the source: the Myojin cycle and Zhao ------------------------

MYOJIN_RAGE = "Myojin of Infinite Rage"
MYOJIN_WEB = "Myojin of Life's Web"
ZHAO = "Zhao, the Moon Slayer"


def _has(chars, keyword: str) -> bool:
    return any(line.lower() == keyword.lower() for line in chars.abilities)


def test_myojin_with_a_divinity_counter_is_indestructible():
    scenario = _board([MYOJIN_RAGE], [])
    myojin = scenario.find(MYOJIN_RAGE, Zone.BATTLEFIELD, "alice")
    assert not _has(_chars(scenario, MYOJIN_RAGE), "Indestructible")
    myojin.add_counters("divinity")
    assert _has(_chars(scenario, MYOJIN_RAGE), "Indestructible")
    assert scenario.game.continuous_effects.layer_notices == []


def test_flip_removing_the_divinity_counter_ends_indestructible():
    scenario = _board([MYOJIN_WEB], [])
    myojin = scenario.find(MYOJIN_WEB, Zone.BATTLEFIELD, "alice")
    myojin.add_counters("divinity")
    assert _has(_chars(scenario, MYOJIN_WEB), "Indestructible")
    myojin.remove_counters("divinity")
    assert not _has(_chars(scenario, MYOJIN_WEB), "Indestructible")


def test_a_different_counter_kind_does_not_grant_indestructible():
    scenario = _board([MYOJIN_RAGE], [])
    myojin = scenario.find(MYOJIN_RAGE, Zone.BATTLEFIELD, "alice")
    myojin.add_counters("+1/+1")
    assert not _has(_chars(scenario, MYOJIN_RAGE), "Indestructible")


def test_another_creature_with_a_divinity_counter_is_not_indestructible():
    scenario = _board([MYOJIN_RAGE, "Grizzly Bears"], [])
    scenario.find("Grizzly Bears", Zone.BATTLEFIELD, "alice").add_counters("divinity")
    assert not _has(_chars(scenario, "Grizzly Bears"), "Indestructible")


def test_zhao_with_a_conqueror_counter_turns_nonbasic_lands_into_mountains():
    scenario = _board([ZHAO, "Sol Ring"], [], bob_battlefield=["Command Tower"])
    tower = scenario.find("Command Tower", Zone.BATTLEFIELD, "bob")
    assert "Mountain" not in scenario.game.characteristics_of(tower).subtypes
    scenario.find(ZHAO, Zone.BATTLEFIELD, "alice").add_counters("conqueror")
    assert "Mountain" in scenario.game.characteristics_of(tower).subtypes


def test_zhao_without_the_counter_leaves_nonbasic_lands_alone():
    scenario = _board([ZHAO], [], bob_battlefield=["Command Tower"])
    tower = scenario.find("Command Tower", Zone.BATTLEFIELD, "bob")
    assert "Mountain" not in scenario.game.characteristics_of(tower).subtypes


def test_zhao_does_not_touch_basic_lands():
    scenario = _board([ZHAO], [], bob_battlefield=["Forest"])
    scenario.find(ZHAO, Zone.BATTLEFIELD, "alice").add_counters("conqueror")
    forest = scenario.find("Forest", Zone.BATTLEFIELD, "bob")
    assert "Mountain" not in scenario.game.characteristics_of(forest).subtypes


