"""Scenario: Wild Mongrel's "Discard a card: This creature gets +1/+1 and
becomes the color of your choice until end of turn."

The pump and the colour change are both continuous effects generated by a
resolving ability (CR 611.2), one in layer 7c (CR 613.4c, power/toughness)
and one in layer 5 (CR 613.1e, colour) - but the colour is a CR 608.2d choice
made as the ability resolves, not something printed on the card, so there is
no channel for it through `machines/layers.py`'s text-driven registry.
`machines/effects.py`'s `_parse_pump_and_becomes_chosen_color_clause` builds
both `ContinuousEffect`s by hand instead, through `ContinuousEffects.add` -
the escape hatch its own docstring names for exactly this ("a caller that is
not going through the registry").

Every rule cited here was looked up with `knowledge_search(q="...",
type="rules")` in the session that wrote this file:

- **CR 701.9a** - "To discard a card, move it from its owner's hand to that
  player's graveyard" - the activation cost, already generic (`ComponentKind.
  DISCARD`).
- **CR 613.1e** - layer 5, colour-changing effects.
- **CR 613.4c** - sublayer 7c, effects that modify (not set) power and
  toughness.
- **CR 611.2a** - a continuous effect from a resolving ability lasts as
  stated - "until end of turn" here.
- **CR 514.2** - "until end of turn" effects end in the cleanup step.
- **CR 608.2d** - "the player announces these [choices] while applying the
  effect" - the colour of choice.
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.models import Color, Zone

from .harness import Scenario


def _scenario() -> Scenario:
    return (
        Scenario()
        .player(
            "alice",
            hand=["Wild Mongrel", "Lightning Bolt", "Opt"],
            battlefield=["Forest", "Forest"],
        )
        .player("bob")
    )


def test_discarding_pumps_the_mongrel_and_changes_its_color():
    scenario = _scenario().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    forests = scenario.untapped_sources("Forest", "Forest")
    mongrel = scenario.cast_and_resolve("Wild Mongrel", *forests)

    bolt = scenario.find("Lightning Bolt", Zone.HAND, "alice")
    scenario.will_choose(Color.BLUE.value, source="Wild Mongrel")
    scenario.activate(mongrel, discarding=[bolt])
    scenario.resolve_top()

    assert mongrel.zone is Zone.BATTLEFIELD
    assert bolt.zone is Zone.GRAVEYARD
    chars = scenario.game.characteristics_of(mongrel)
    assert chars.power == 3
    assert chars.toughness == 3
    assert chars.colors == (Color.BLUE,)


def test_the_pump_and_color_change_both_end_at_cleanup():
    scenario = _scenario().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    forests = scenario.untapped_sources("Forest", "Forest")
    mongrel = scenario.cast_and_resolve("Wild Mongrel", *forests)

    opt = scenario.find("Opt", Zone.HAND, "alice")
    scenario.will_choose(Color.BLACK.value, source="Wild Mongrel")
    scenario.activate(mongrel, discarding=[opt])
    scenario.resolve_top()
    chars = scenario.game.characteristics_of(mongrel)
    assert chars.power == 3
    assert chars.colors == (Color.BLACK,)

    scenario.game.continuous_effects.end_the_turn()

    chars = scenario.game.characteristics_of(mongrel)
    assert chars.power == 2
    assert chars.toughness == 2
    assert chars.colors == (Color.GREEN,)


def test_activating_twice_stacks_the_pump():
    """CR 611.2c fixes each activation as its own effect - two activations
    are two +1/+1 pumps, not one that overwrites the other."""
    scenario = _scenario().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    forests = scenario.untapped_sources("Forest", "Forest")
    mongrel = scenario.cast_and_resolve("Wild Mongrel", *forests)

    bolt = scenario.find("Lightning Bolt", Zone.HAND, "alice")
    opt = scenario.find("Opt", Zone.HAND, "alice")
    scenario.will_choose(Color.BLUE.value, source="Wild Mongrel", times=1)
    scenario.activate(mongrel, discarding=[bolt])
    scenario.resolve_top()
    scenario.will_choose(Color.RED.value, source="Wild Mongrel", times=1)
    scenario.activate(mongrel, discarding=[opt])
    scenario.resolve_top()

    chars = scenario.game.characteristics_of(mongrel)
    assert chars.power == 4
    assert chars.toughness == 4
    assert chars.colors == (Color.RED,)


def test_discarding_with_an_empty_hand_is_refused():
    """CR 118.3: a discard cost cannot be paid with no card to discard."""
    scenario = (
        Scenario()
        .player("alice", hand=["Wild Mongrel"], battlefield=["Forest", "Forest"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    forests = scenario.untapped_sources("Forest", "Forest")
    mongrel = scenario.cast_and_resolve("Wild Mongrel", *forests)

    payment = scenario.game.begin_activating(mongrel, 0, "alice")
    with pytest.raises(ValueError):
        payment.pay()
