def _equip(scenario, equipment, target, *sources):
    activation = equip_activation(scenario.game, equipment, target, "alice")
    payment = activation.begin_paying()
    for source in sources:
        payment.tap_for_mana(source, mana_from(source))
    payment.pay()
    activation.activate()
    scenario.resolve_top()
    return activation


def test_kili_without_a_story_pays_the_printed_equip_cost():
    scenario = (
        Scenario()
        .player("alice", battlefield=["Kíli the Resourceful", "Bonesplitter", "Plains"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bonesplitter = scenario.find("Bonesplitter", Zone.BATTLEFIELD, "alice")
    kili = scenario.creature("Kíli the Resourceful")
    activation = equip_activation(scenario.game, bonesplitter, kili, "alice")
    assert str(activation.cost.mana) == "{1}"


