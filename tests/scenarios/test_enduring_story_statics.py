#: Two more permanents that count toward storied (CR 702.195a): with the
#: storied legend itself, three.
STORY = ["Mox Amber", "Darksteel Relic"]


def _with_story(scenario):
    scenario.game.check_state_based_actions()
    return scenario


# --------------------------------------------------------------------------
# Layer 7c anthem: Fili the Pathfinder
# --------------------------------------------------------------------------


def test_fili_anthem_is_off_without_a_story():
    scenario = _with_story(
        Scenario().player("alice", battlefield=["Fíli the Pathfinder", "Grizzly Bears"]).build()
    )
    assert scenario.player("alice").has_enduring_story is False
    assert scenario.creature("Grizzly Bears").power == 2
    assert scenario.creature("Fíli the Pathfinder").power == 2


def test_fili_anthem_pumps_every_creature_you_control_with_a_story():
    scenario = _with_story(
        Scenario()
        .player("alice", battlefield=["Fíli the Pathfinder", "Grizzly Bears", *STORY])
        .player("bob", battlefield=["Grizzly Bears"])
        .build()
    )
    assert scenario.player("alice").has_enduring_story is True
    bears = scenario.creature("Grizzly Bears", "alice")
    assert (bears.power, bears.toughness) == (3, 3)
    fili = scenario.creature("Fíli the Pathfinder", "alice")
    assert (fili.power, fili.toughness) == (3, 3)
    theirs = scenario.creature("Grizzly Bears", "bob")
    assert (theirs.power, theirs.toughness) == (2, 2), "you control - not bob's"


def test_an_opponents_story_does_not_switch_on_your_anthem():
    """ "you have": the gate reads the static's own controller's designation,
    never an opponent's."""
    scenario = _with_story(
        Scenario()
        .player("alice", battlefield=["Fíli the Pathfinder", "Grizzly Bears"])
        .player("bob", battlefield=["Ori, Keeper of Songs", *STORY])
        .build()
    )
    assert scenario.player("bob").has_enduring_story is True
    assert scenario.player("alice").has_enduring_story is False
    assert scenario.creature("Grizzly Bears", "alice").power == 2


def test_the_anthem_stays_on_after_the_count_drops():
    """The story outlives the permanents that earned it (CR 702.195b), so the
    gated anthem does too."""
    scenario = _with_story(
        Scenario()
        .player("alice", battlefield=["Fíli the Pathfinder", "Grizzly Bears", *STORY])
        .build()
    )
    for name in STORY:
        scenario.game.sacrifice(scenario.find(name, Zone.BATTLEFIELD, "alice"))
    scenario.game.check_state_based_actions()
    assert scenario.creature("Grizzly Bears").power == 3


def test_the_anthem_leaves_with_fili():
    """CR 604.2: the gate only narrows Fili's own static ability, which ends
    when Fili leaves - the story alone pumps nothing."""
    scenario = _with_story(
        Scenario()
        .player("alice", battlefield=["Fíli the Pathfinder", "Grizzly Bears", *STORY])
        .build()
    )
    scenario.game.sacrifice(scenario.creature("Fíli the Pathfinder"))
    assert scenario.player("alice").has_enduring_story is True
    assert scenario.creature("Grizzly Bears").power == 2


