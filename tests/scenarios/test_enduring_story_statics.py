"""Statics gated on an enduring story (CR 702.195b's designation): "As long
as you have an enduring story, `<static>`" and "`<static>` unless you have an
enduring story", each rider on the Hobbit Dwarf that prints it -

- Fili the Pathfinder: "... creatures you control get +1/+1." (layer 7c)
- Ori, Keeper of Songs / Oin the Brave: "... Ori gets +1/+0 and has
  vigilance." / "... Oin gets +1/+0 and has haste." (layers 7c and 6)
- Thorin Oakenshield: "... artifacts and creatures you control have ward
  {1}." (layer 6), with Dragon's Disciple's ungated "Dragons you control have
  ward {1}." proving the costed-ward group grant
- Bombur, Gentle Dreamer: "Bombur doesn't untap during your untap step
  unless you have an enduring story." (CR 502.3)
- Dain, Lord of the Iron Hills: "... creatures can't attack you unless their
  controller pays {1} for each of those creatures." (CR 508.1h), with Ghostly
  Prison's ungated "{2} for each creature they control that's attacking you"
- Kili the Resourceful: "... you may pay {0} rather than pay the equip cost
  of the first equip ability you activate each turn." (CR 702.6a), with
  Forge Anew's ungated "during each of your turns"

Every rule cited here was read whole with `mise run rules:find` in the
session that wrote this file:

- **CR 604.2** - a static ability's effects "are active as long as the
  permanent with the ability remains on the battlefield and has the ability".
- **CR 611.3a** - "A continuous effect generated by a static ability isn't
  'locked in'; it applies at any given moment to whatever its text
  indicates." - the gate is asked afresh on every computation.
- **CR 702.195b** - enduring story is a designation, set once and never
  cleared.
- **CR 502.3** - "effects can keep one or more of a player's permanents from
  untapping".
- **CR 508.1d** - "If a creature can't attack unless a player pays a cost,
  that player is not required to pay that cost, even if attacking with that
  creature would increase the number of requirements being obeyed."
- **CR 508.1h** - "If any of the chosen creatures require paying costs to
  attack ... the active player determines the total cost to attack."
- **CR 508.1j** - "Once the player has enough mana in their mana pool, they
  pay all costs in any order. Partial payments are not allowed."
- **CR 702.6a** - "Equip [cost]" means "[Cost]: Attach this permanent to
  target creature you control. Activate only as a sorcery."
- **CR 702.21a** - ward's counter unless that player pays.
"""

