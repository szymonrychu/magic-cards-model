def _attack_board(defender_cards: list[str], lands: int = 4) -> Scenario:
    return (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            battlefield=["Grizzly Bears", "Savannah Lions", *["Plains"] * lands],
        )
        .player("bob", battlefield=defender_cards)
    )


def _ready(scenario):
    scenario.game.check_state_based_actions()
    scenario.start_at(Step.DECLARE_ATTACKERS)
    for creature in scenario.game.permanents_controlled_by("alice"):
        creature.summoning_sick = False
    return scenario


def test_dain_without_a_story_taxes_nothing():
    scenario = _ready(_attack_board(["Dáin, Lord of the Iron Hills"]).build())
    bears = scenario.creature("Grizzly Bears", "alice")
    lions = scenario.creature("Savannah Lions", "alice")
    scenario.attack_with(bears, lions)
    assert all(not land.tapped for land in scenario.untapped_sources("Plains", username="alice"))
    assert len(scenario.attackers()) == 2


def test_dain_with_a_story_charges_one_per_attacker():
    scenario = _ready(_attack_board(["Dáin, Lord of the Iron Hills", *STORY]).build())
    assert scenario.player("bob").has_enduring_story is True
    bears = scenario.creature("Grizzly Bears", "alice")
    lions = scenario.creature("Savannah Lions", "alice")
    scenario.attack_with(bears, lions)
    tapped = [
        land
        for land in scenario.game.permanents_controlled_by("alice")
        if land.name == "Plains" and land.tapped
    ]
    assert len(tapped) == 2, "{1} for each of the two attackers (CR 508.1h)"
    assert len(scenario.attackers()) == 2


def test_an_unpayable_attack_cost_makes_the_declaration_illegal():
    """CR 508.1j: "Partial payments are not allowed" - one Plains cannot pay
    {2}, the declaration is refused, and nothing taps (CR 508.1)."""
    scenario = _ready(_attack_board(["Dáin, Lord of the Iron Hills", *STORY], lands=1).build())
    bears = scenario.creature("Grizzly Bears", "alice")
    lions = scenario.creature("Savannah Lions", "alice")
    with pytest.raises(ValueError, match="CR 508.1"):
        scenario.attack_with(bears, lions)
    assert not bears.tapped and not lions.tapped
    assert scenario.attackers() == []
    assert not scenario.find("Plains", Zone.BATTLEFIELD, "alice").tapped


def test_one_attacker_is_affordable_where_two_are_not():
    scenario = _ready(_attack_board(["Dáin, Lord of the Iron Hills", *STORY], lands=1).build())
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.attack_with(bears)
    assert scenario.attackers() == [bears]
    assert scenario.find("Plains", Zone.BATTLEFIELD, "alice").tapped


