"""CR 611.2a's longer "until your next turn" duration on a single-target pump,
as opposed to the ordinary "until end of turn" `_PUMP_RE` shape sits beside in
`machines/layers.py`.

Verified this session with `mise run rules:find`:

- **CR 611.2a** - "A continuous effect generated by the resolution of a spell
  or ability lasts as long as stated by the spell or ability creating it
  (such as 'until end of turn'). If no duration is stated, it lasts until the
  end of the game." "Until your next turn" is the same rule with a longer
  stated span than the ordinary "until end of turn" example the rule itself
  gives - the ending moment is the *start* of the granting player's next
  turn, not that turn's own cleanup, exactly what the printed words say.
  (Not CR 800.4m, which reads similarly but is scoped to what happens to such
  a duration when the player it names has left the game entirely - this file
  never has a player leave.)
- **CR 514.2** - the cleanup step, "all 'until end of turn' ... effects end".
  An `UNTIL_YOUR_NEXT_TURN` effect is not one of those, so it is not touched
  there - it is `Game.begin_turn_for` (called from the untap step) that ends
  it, per CR 611.2a above.
- **CR 115.6** - "A spell or ability that requires targets may allow zero
  targets to be chosen." - "up to one target" permits zero or one; the
  parametrized cards choose exactly one, and Jace's own case below chooses
  none.

Two real printings, same shape, different numbers and different card type of
origin (a `+2` and a `+1`, both loyalty abilities):

- **Garruk, Veiled Butcher** - `+2: Up to one target creature gets -4/-1
  until your next turn.`
- **Liliana, the Last Hope** - `+1: Up to one target creature gets -2/-1
  until your next turn.` - the off-set proof that the parser reads the shape
  and not this one card's exact sentence: a different planeswalker, a
  different loyalty cost, and a different magnitude.
- **Jace, Telepath Unbound** (the back face of Jace, Vryn's Prodigy) -
  `+1: Up to one target creature gets -2/-0 until your next turn.` - the same
  shape on a transformed double-faced card, whose line the sweep used to judge
  against the creature face's text and so reported silent.

Both cards' only loyalty ability before this one on the stack is a static
line (Garruk's exile-replacement, absent on Liliana), which `activated_
abilities` never counts - so both pumps are activated ability index 0, on a
freshly-entered walker, no mana required (CR 606.4: the cost is only the
loyalty counters).
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone
from magic_cards_model.models.card import Type
from magic_cards_model.models.card_state import Counter
from magic_cards_model.support import classify_clauses
from tests.cards import card
from tests.scenarios.harness import Scenario

PUMP_CARDS = [
    pytest.param("Garruk, Veiled Butcher", -4, -1, id="garruk"),
    pytest.param("Liliana, the Last Hope", -2, -1, id="liliana"),
    pytest.param("Jace, Vryn's Prodigy", -2, 0, id="jace"),
]


def _board(card_name: str) -> Scenario:
    """`automatic_turn_based_actions` is on by default (CR 703.3's own actions
    happen on their own), which is exactly what a multi-turn walk needs here -
    it is what runs `Game.begin_turn_for` from inside the untap step, and
    CR 611.2a's clock lives there. A handful of basics per player keeps the
    automatic draw step (CR 704.5b) from ending the game partway through a
    walk that crosses two or three turns."""
    return (
        Scenario()
        .player("alice", battlefield=[card_name], library=["Forest"] * 5)
        .player("bob", battlefield=["Grizzly Bears"], library=["Forest"] * 5)
        .build()
    )


def _walker(scenario: Scenario, card_name: str):
    """The walker on alice's side. A double-faced card whose planeswalker is
    its back face (Jace, Vryn's Prodigy // Jace, Telepath Unbound) is turned
    to that face first - CR 712.8e: with its back face up it has only that
    face's characteristics."""
    walker = scenario.find(card_name, Zone.BATTLEFIELD, "alice")
    if Type.PLANESWALKER not in scenario.game.characteristics_of(walker).types:
        walker.transformed = True
        walker.add_counters(Counter.LOYALTY, int(walker.up_face.loyalty or 0))
    return walker


def _activate_the_pump(scenario: Scenario, card_name: str, target) -> None:
    """Activate the walker's own index-0 loyalty ability, targeting `target`."""
    walker = _walker(scenario, card_name)
    scenario.activate(walker, index=0, username="alice", targets=[target])
    scenario.pass_until_resolved()


def _advance_until(scenario: Scenario, predicate) -> None:
    """Advance until `predicate(scenario)` holds. `automatic_turn_based_actions`
    is on (the default), so every step's own CR 703.3 action - including the
    untap step's `Game.begin_turn_for`, where CR 611.2a's clock lives - runs
    as each step is reached, with no attacker ever auto-declared (CR 508.1a:
    an unscripted declaration is "no attackers")."""
    while not predicate(scenario):
        scenario.advance()


# --------------------------------------------------------------------------
# The pump applies immediately
# --------------------------------------------------------------------------


@pytest.mark.parametrize(("card_name", "power", "toughness"), PUMP_CARDS)
def test_the_pump_applies_immediately_on_resolution(
    card_name: str, power: int, toughness: int
) -> None:
    scenario = _board(card_name)
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")

    _activate_the_pump(scenario, card_name, bears)

    characteristics = scenario.game.characteristics_of(bears)
    assert (characteristics.power, characteristics.toughness) == (2 + power, 2 + toughness)


# --------------------------------------------------------------------------
# It outlasts an ordinary "until end of turn" cleanup - both the activating
# player's own, and the opponent's whole intervening turn.
# --------------------------------------------------------------------------


@pytest.mark.parametrize(("card_name", "power", "toughness"), PUMP_CARDS)
def test_the_pump_survives_the_activating_players_own_cleanup(
    card_name: str, power: int, toughness: int
) -> None:
    """CR 514.2's cleanup ends every "until end of turn" effect. This is not
    one, so alice's own end-of-turn cleanup - the very first cleanup step
    reached after the ability resolves - leaves it standing, unlike a plain
    `_PUMP_RE` "until end of turn" pump would be."""
    scenario = _board(card_name)
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")
    _activate_the_pump(scenario, card_name, bears)

    # CLEANUP's own CR 514 action already ran as this step was reached
    # (automatic_turn_based_actions).
    _advance_until(scenario, lambda s: s.turn.active_player == "alice" and s.step is Step.CLEANUP)

    characteristics = scenario.game.characteristics_of(bears)
    assert (characteristics.power, characteristics.toughness) == (2 + power, 2 + toughness)


@pytest.mark.parametrize(("card_name", "power", "toughness"), PUMP_CARDS)
def test_the_pump_survives_through_the_opponents_entire_next_turn(
    card_name: str, power: int, toughness: int
) -> None:
    """CR 611.2a: the pump outlasts the rest of alice's own turn *and* all of
    bob's turn in between, including bob's own cleanup - it ends only when
    alice's own next turn begins."""
    scenario = _board(card_name)
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")
    _activate_the_pump(scenario, card_name, bears)

    # CLEANUP's own CR 514 action already ran as this step was reached
    # (automatic_turn_based_actions).
    _advance_until(scenario, lambda s: s.turn.active_player == "bob" and s.step is Step.CLEANUP)

    characteristics = scenario.game.characteristics_of(bears)
    assert (characteristics.power, characteristics.toughness) == (2 + power, 2 + toughness)


# --------------------------------------------------------------------------
# It ends exactly when alice's own next turn *begins* - not at that turn's
# own cleanup.
# --------------------------------------------------------------------------


@pytest.mark.parametrize(("card_name", "power", "toughness"), PUMP_CARDS)
def test_the_pump_ends_the_instant_the_controllers_own_next_turn_begins(
    card_name: str, power: int, toughness: int
) -> None:
    """`Game.begin_turn_for` runs from the untap step, before any turn-based
    action of that turn - so the pump is gone the moment alice's own next
    turn is reached, well before that turn would ever get to its own
    cleanup. Checked at the earliest possible step of that turn to make sure
    the boundary really is the turn's *start*."""
    scenario = _board(card_name)
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")
    _activate_the_pump(scenario, card_name, bears)

    turns_taken = scenario.turn.turns_taken
    # Walk past bob's whole turn and into alice's next one.
    _advance_until(
        scenario,
        lambda s: s.turn.turns_taken > turns_taken and s.turn.active_player == "alice",
    )

    characteristics = scenario.game.characteristics_of(bears)
    assert (characteristics.power, characteristics.toughness) == (2, 2), (
        "alice's own next turn has begun, so CR 611.2a's stated duration is already over - "
        "not merely pending until this turn's own cleanup"
    )


# --------------------------------------------------------------------------
# "Up to one" may choose none, and the sweep reads a back face's own line
# --------------------------------------------------------------------------


def test_jace_may_choose_no_target_and_still_gains_the_loyalty() -> None:
    """CR 115.6: "up to one" legally chooses zero; the +1 still costs (adds)
    its loyalty and pumps nothing."""
    scenario = _board("Jace, Vryn's Prodigy")
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")
    walker = _walker(scenario, "Jace, Vryn's Prodigy")
    scenario.activate(walker, index=0, username="alice", targets=[])
    scenario.pass_until_resolved()

    assert walker.counters[Counter.LOYALTY] == 6
    characteristics = scenario.game.characteristics_of(bears)
    assert (characteristics.power, characteristics.toughness) == (2, 2)


def test_the_sweep_reads_the_back_face_pump_off_its_own_line() -> None:
    """The +1 is printed on Jace, Telepath Unbound; `create_continuous_effect_
    of_ability` reads the ability's own text at resolution, and the sweep has
    to judge the same text rather than the creature face's."""
    outcomes = {
        outcome.text: outcome.category for outcome in classify_clauses(card("Jace, Vryn's Prodigy"))
    }
    assert outcomes["+1: Up to one target creature gets -2/-0 until your next turn."] == "handled"
