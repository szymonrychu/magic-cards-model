"""Scenario: next-N prevention shields - "Prevent the next N damage that
would be dealt to <you | target creature | any target> this turn[, where X is
<amount>][ by a source of your choice]."

Rules, each read in full with `mise run rules:find`:

- CR 615.7 - "Some prevention effects generated by the resolution of a spell
  or ability refer to a specific amount of damage ... These work like
  shields. Each 1 damage that would be dealt to the "shielded" permanent or
  player is prevented. Preventing 1 damage reduces the remaining shield by 1.
  ... Such effects count only the amount of damage; the number of events or
  sources dealing it doesn't matter."
- CR 107.3a - "While a spell is on the stack, any X in its mana cost ...
  equals the announced value. While an activated ability is on the stack, any
  X in its activation cost equals the announced value."
- CR 700.5 - "A player's devotion to [color] is equal to the number of mana
  symbols of that color among the mana costs of permanents that player
  controls."
- CR 608.2h - "If an effect requires information from the game ..., the
  answer is determined only once, when the effect is applied." - X is fixed
  as the shield is created.
- CR 609.7a - "If an effect requires a player to choose a source of damage,
  they may choose a permanent; a spell on the stack ... The source is chosen
  when the effect is created."
- CR 514.2 - "this turn" effects end in the cleanup step.

Listed printings: Festival of the Guildpact (X to you), Acolyte's Reward
(where X is your devotion to white), Healing Grace (any target, a source of
your choice). Proof printings, none listed, none in an api deck, all legal in
Modern: Reinforced Bulwark ("{T}: Prevent the next 1 damage that would be
dealt to you this turn."), Esper Battlemage ("{W}, {T}: ... the next 2
..."), Palliation Accord ("Remove a palliation counter ...: ... the next 1
...").
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone
from magic_cards_model.support import card_support
from tests.cards import card

from .harness import Scenario


@pytest.mark.parametrize(
    "name",
    [
        "Festival of the Guildpact",
        "Healing Grace",
        "Reinforced Bulwark",
        "Esper Battlemage",
        "Palliation Accord",
    ],
)
def test_every_listed_and_proof_card_reads_handled(name):
    outcomes = {clause.outcome for clause in card_support(card(name)).clauses}
    assert outcomes == {"handled"}, name


def _board(*, alice_battlefield=(), bob_battlefield=(), alice_hand=(), bob_hand=()):
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=list(alice_hand),
            battlefield=[*["Plains"] * 6, *alice_battlefield],
            library=["Plains"] * 8,
        )
        .player(
            "bob",
            hand=list(bob_hand),
            battlefield=[*["Mountain"] * 4, *bob_battlefield],
            library=["Mountain"] * 8,
        )
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


def _bob_casts(scenario, name, target):
    if scenario.priority_holder != "bob":
        scenario.pass_priority(scenario.priority_holder)
    return scenario.cast_and_resolve(name, username="bob", targets=[target], auto=True)


def _festival(scenario, x):
    if scenario.priority_holder != "alice":
        scenario.pass_priority(scenario.priority_holder)
    scenario.game.cast(
        scenario.find("Festival of the Guildpact", Zone.HAND, "alice"),
        "alice",
        x_value=x,
        mana_sources=scenario.untapped_sources(*["Plains"] * (x + 1), username="alice"),
    )
    return scenario.resolve_top()


# -- Festival of the Guildpact: the next X to you ------------------------------


def test_festival_prevents_the_next_x_damage_to_you_and_draws():
    scenario = _board(alice_hand=["Festival of the Guildpact"], bob_hand=["Lightning Bolt"])
    hand_before = len(scenario.player("alice").hand)

    _festival(scenario, 3)
    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 20
    # Festival left the hand, one card was drawn.
    assert len(scenario.player("alice").hand) == hand_before


def test_festival_shield_smaller_than_the_damage_lets_the_rest_through():
    scenario = _board(alice_hand=["Festival of the Guildpact"], bob_hand=["Lightning Bolt"])

    _festival(scenario, 2)
    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 19


def test_festival_shield_is_spread_over_several_events():
    scenario = _board(
        alice_hand=["Festival of the Guildpact"], bob_hand=["Lightning Bolt", "Shock"]
    )

    _festival(scenario, 4)
    _bob_casts(scenario, "Lightning Bolt", "alice")  # 3 of the 4 used
    _bob_casts(scenario, "Shock", "alice")  # 1 prevented, 1 dealt

    assert scenario.player("alice").life == 19


def test_festival_shields_you_and_not_your_creatures():
    scenario = _board(
        alice_hand=["Festival of the Guildpact"],
        alice_battlefield=["Hill Giant"],
        bob_hand=["Shock"],
    )
    giant = scenario.creature("Hill Giant", "alice")

    _festival(scenario, 3)
    _bob_casts(scenario, "Shock", giant)

    assert giant.damage == 2
    assert scenario.player("alice").life == 20


def test_festival_with_x_zero_prevents_nothing():
    scenario = _board(alice_hand=["Festival of the Guildpact"], bob_hand=["Shock"])

    _festival(scenario, 0)
    _bob_casts(scenario, "Shock", "alice")

    assert scenario.player("alice").life == 18


# -- Acolyte's Reward: where X is your devotion to white -----------------------


def _acolytes_reward(scenario, shielded, rider):
    if scenario.priority_holder != "alice":
        scenario.pass_priority(scenario.priority_holder)
    return scenario.cast_and_resolve(
        "Acolyte's Reward", username="alice", targets=[shielded, rider], auto=True
    )


def test_acolytes_reward_shield_is_your_devotion_to_white():
    # Serra Angel {3}{W}{W} and Savannah Lions {W}: devotion to white 3.
    scenario = _board(
        alice_hand=["Acolyte's Reward"],
        alice_battlefield=["Serra Angel", "Savannah Lions"],
        bob_hand=["Lightning Bolt", "Shock"],
    )
    angel = scenario.creature("Serra Angel", "alice")

    _acolytes_reward(scenario, angel, "bob")
    _bob_casts(scenario, "Lightning Bolt", angel)
    _bob_casts(scenario, "Shock", angel)

    # 3 of the 5 prevented, 2 dealt.
    assert angel.damage == 2


def test_acolytes_reward_devotion_is_fixed_as_the_shield_is_made():
    scenario = _board(
        alice_hand=["Acolyte's Reward"],
        alice_battlefield=["Serra Angel", "Savannah Lions"],
        bob_hand=["Lightning Bolt"],
    )
    angel = scenario.creature("Serra Angel", "alice")
    lions = scenario.creature("Savannah Lions", "alice")

    _acolytes_reward(scenario, angel, "bob")
    scenario.game.return_to_hand(lions)  # devotion now 2, the shield stays 3
    _bob_casts(scenario, "Lightning Bolt", angel)

    assert angel.damage == 0


def test_acolytes_reward_with_no_devotion_prevents_nothing():
    scenario = _board(
        alice_hand=["Acolyte's Reward"],
        alice_battlefield=["Hill Giant"],
        bob_hand=["Shock"],
    )
    giant = scenario.creature("Hill Giant", "alice")

    _acolytes_reward(scenario, giant, "bob")
    _bob_casts(scenario, "Shock", giant)

    assert giant.damage == 2
    assert scenario.player("bob").life == 20


# -- Healing Grace: any target, a source of your choice ------------------------


def _healing_grace(scenario, target, source):
    if scenario.priority_holder != "alice":
        scenario.pass_priority(scenario.priority_holder)
    scenario.will_choose_cards(source, username="alice")
    return scenario.cast_and_resolve("Healing Grace", username="alice", targets=[target], auto=True)


def test_healing_grace_prevents_the_chosen_spells_damage_to_you_and_gains_three():
    scenario = _board(alice_hand=["Healing Grace"], bob_hand=["Lightning Bolt"])
    scenario.pass_priority("alice")
    bolt = scenario.cast_onto_stack("Lightning Bolt", username="bob", targets=["alice"], auto=True)
    scenario.pass_priority("bob")
    _healing_grace(scenario, "alice", bolt)

    scenario.resolve_top()

    assert scenario.player("alice").life == 23


def test_healing_grace_does_not_prevent_another_sources_damage():
    scenario = _board(alice_hand=["Healing Grace"], bob_hand=["Lightning Bolt"])
    other_source = scenario.untapped_sources("Mountain", username="bob")[0]

    _healing_grace(scenario, "alice", other_source)
    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 20  # 23 after the life, then 3 dealt


def test_healing_grace_shields_a_creature_from_the_chosen_attacker_only():
    scenario = _board(
        alice_hand=["Healing Grace"],
        alice_battlefield=["Watchwolf"],
        bob_battlefield=["Hill Giant", "Gray Ogre"],
    )
    wolf = scenario.creature("Watchwolf", "alice")
    giant = scenario.creature("Hill Giant", "bob")
    ogre = scenario.creature("Gray Ogre", "bob")
    _healing_grace(scenario, wolf, giant)

    scenario.attack_with(wolf, defending="bob")
    scenario.block(wolf, giant, ogre)
    scenario.combat_damage()

    # The Giant's 3 prevented, the Ogre's 2 dealt.
    assert wolf.damage == 2
    assert wolf.zone is Zone.BATTLEFIELD


def test_healing_grace_shield_is_three_from_the_chosen_source():
    scenario = _board(
        alice_hand=["Healing Grace"],
        alice_battlefield=["Serra Angel"],
        bob_battlefield=["Walking Ballista"],
    )
    angel = scenario.creature("Serra Angel", "alice")
    ballista = scenario.creature("Walking Ballista", "bob")
    scenario.game.add_counters(ballista, "+1/+1", 4)
    _healing_grace(scenario, angel, ballista)

    for _ in range(4):
        if scenario.priority_holder != "bob":
            scenario.pass_priority(scenario.priority_holder)
        scenario.activate(ballista, index=1, username="bob", targets=[angel])
        scenario.resolve_top()

    assert angel.damage == 1


# -- the activated next-N-to-you proofs -----------------------------------------


def test_reinforced_bulwark_prevents_the_next_one_damage_to_you():
    scenario = _board(alice_battlefield=["Reinforced Bulwark"], bob_hand=["Lightning Bolt"])
    bulwark = scenario.find("Reinforced Bulwark", Zone.BATTLEFIELD, "alice")
    scenario.activate(bulwark, username="alice")
    scenario.resolve_top()

    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 18


def test_esper_battlemage_prevents_the_next_two_damage_to_you():
    scenario = _board(alice_battlefield=["Esper Battlemage"], bob_hand=["Lightning Bolt"])
    battlemage = scenario.find("Esper Battlemage", Zone.BATTLEFIELD, "alice")
    scenario.activate(battlemage, index=0, username="alice", auto=True)
    scenario.resolve_top()

    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 19


def test_palliation_accord_counter_buys_one_point_of_prevention():
    scenario = _board(alice_battlefield=["Palliation Accord"], bob_hand=["Lightning Bolt"])
    accord = scenario.find("Palliation Accord", Zone.BATTLEFIELD, "alice")
    scenario.game.add_counters(accord, "palliation", 2)
    scenario.activate(accord, index=0, username="alice")
    scenario.resolve_top()
    scenario.activate(accord, index=0, username="alice")
    scenario.resolve_top()

    _bob_casts(scenario, "Lightning Bolt", "alice")

    assert scenario.player("alice").life == 19
    assert accord.counters["palliation"] == 0


def test_a_next_n_shield_to_you_ends_with_the_turn():
    scenario = _board(alice_battlefield=["Reinforced Bulwark"])
    bulwark = scenario.find("Reinforced Bulwark", Zone.BATTLEFIELD, "alice")
    scenario.activate(bulwark, username="alice")
    scenario.resolve_top()

    turns = scenario.turn.turns_taken
    while scenario.turn.turns_taken == turns:
        scenario.advance()
        while not scenario.game.stack_is_empty:
            scenario.resolve_top()

    assert scenario.game.active_prevention_shields() == []
