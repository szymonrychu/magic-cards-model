"""A self pump gated on its controller's life total: "As long as you have 30 or
more life, this creature gets +5/+5 and has flying." (Serra Ascendant), and the
trailing form "This creature gets +4/+4 as long as you have 25 or more life."
(Divinity of Pride - the second printing, legal in Modern, in no deck in the
api's pool).

Every CR number below was looked up with `mise run rules:find` in the session
that wrote this file:

- **CR 604.2** - static abilities' effects "are active as long as the
  permanent with the ability remains on the battlefield and has the ability".
- **CR 611.3a** - "A continuous effect generated by a static ability isn't
  'locked in'; it applies at any given moment to whatever its text indicates."
  The life total is read on every computation.
- **CR 613.4c** - "Layer 7c: Effects and counters that modify power and/or
  toughness ... are applied." The pump.
- **CR 613.1f** - "Layer 6: Ability-adding effects ..." The flying.
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.support import HANDLED, classify_clauses
from tests.cards import card
from tests.scenarios.harness import PlayedScenario, Scenario


def stats(scenario: PlayedScenario, name: str, username: str) -> tuple[int, int, tuple[str, ...]]:
    """Power, toughness and the keyword names its computed abilities start
    with (reminder text dropped)."""
    chars = scenario.game.characteristics_of(scenario.creature(name, username))
    keywords = tuple(line.split(" (")[0] for line in chars.abilities)
    return chars.power, chars.toughness, keywords


def board(name: str, life: int, *, bob_life: int = 20) -> PlayedScenario:
    scenario = (
        Scenario()
        .player("alice", life=life, battlefield=[name], library=["Plains"] * 5)
        .player("bob", life=bob_life, library=["Plains"] * 5)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


@pytest.mark.parametrize("name", ["Serra Ascendant", "Divinity of Pride"])
def test_the_life_threshold_line_is_handled(name: str) -> None:
    (clause,) = [c for c in classify_clauses(card(name)) if "or more life" in c.text]

    assert clause.category == HANDLED


def test_at_the_threshold_it_is_pumped_and_flies() -> None:
    """ "30 or more" - exactly 30 counts."""
    scenario = board("Serra Ascendant", 30)

    power, toughness, abilities = stats(scenario, "Serra Ascendant", "alice")

    assert (power, toughness) == (6, 6)
    assert "Flying" in abilities
    assert "Lifelink" in abilities


def test_below_the_threshold_it_is_unchanged() -> None:
    scenario = board("Serra Ascendant", 29)

    power, toughness, abilities = stats(scenario, "Serra Ascendant", "alice")

    assert (power, toughness) == (1, 1)
    assert "Flying" not in abilities
    assert "Lifelink" in abilities


def test_an_opponent_s_life_does_not_count() -> None:
    """ "you have" is the controller's own life total."""
    scenario = board("Serra Ascendant", 20, bob_life=40)

    assert stats(scenario, "Serra Ascendant", "alice")[:2] == (1, 1)


def test_gaining_life_to_the_threshold_turns_it_on_at_once() -> None:
    """CR 611.3a: not locked in - the next computation sees the new total."""
    scenario = board("Serra Ascendant", 25)
    assert stats(scenario, "Serra Ascendant", "alice")[:2] == (1, 1)

    scenario.game.gain_life(scenario.player("alice"), 5)

    assert stats(scenario, "Serra Ascendant", "alice")[:2] == (6, 6)


def test_losing_life_below_the_threshold_turns_it_off() -> None:
    scenario = board("Serra Ascendant", 31)
    assert stats(scenario, "Serra Ascendant", "alice")[:2] == (6, 6)

    scenario.player("alice").lose_life(2)

    power, toughness, abilities = stats(scenario, "Serra Ascendant", "alice")
    assert (power, toughness) == (1, 1)
    assert "Flying" not in abilities


def test_its_own_lifelink_can_carry_it_over_the_threshold() -> None:
    """At 29, an unblocked 1/1 lifelinker gains 1: 30, and it is a 6/6 flyer
    as soon as the damage is dealt."""
    scenario = board("Serra Ascendant", 29)
    ascendant = scenario.creature("Serra Ascendant", "alice")
    ascendant.summoning_sick = False
    scenario.start_at(Step.DECLARE_ATTACKERS)
    scenario.attack_with(ascendant)
    scenario.advance()
    scenario.no_blocks()
    scenario.combat_damage()

    assert scenario.player("bob").life == 19
    assert scenario.player("alice").life == 30
    assert stats(scenario, "Serra Ascendant", "alice")[:2] == (6, 6)


def test_the_trailing_form_pumps_at_its_own_threshold() -> None:
    """Divinity of Pride: "This creature gets +4/+4 as long as you have 25 or
    more life." - condition after the pump, a different threshold, no
    keyword."""
    scenario = board("Divinity of Pride", 25)

    power, toughness, abilities = stats(scenario, "Divinity of Pride", "alice")

    assert (power, toughness) == (8, 8)
    assert "Flying, lifelink" in abilities


def test_the_trailing_form_is_off_below_its_threshold() -> None:
    scenario = board("Divinity of Pride", 24)

    assert stats(scenario, "Divinity of Pride", "alice")[:2] == (4, 4)
