"""An untimed "gain control of target `<object>`." on a triggered ability.

CR 611.2a: "A continuous effect generated by the resolution of a spell or
ability lasts as long as stated by the spell or ability creating it (such as
'until end of turn'). If no duration is stated, it lasts until the end of the
game." The control change is layer 2 (CR 613.1b), and keyed to the object as
it is now (CR 400.7): the permanent leaving and coming back is a new object
its owner controls.

- Agent of Treachery: "When this creature enters, gain control of target
  permanent."
- Keiga, the Tide Star (off-set proof: legal, in no deck list): "When Keiga
  dies, gain control of target creature." - a different trigger, a named
  self-reference and a narrower target.
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone

from .harness import Scenario


def _controller(scenario, permanent):
    return scenario.game.controller_of(permanent).username


def _next_turn(scenario):
    turns = scenario.turn.turns_taken
    while scenario.turn.turns_taken == turns:
        scenario.advance()
        while not scenario.game.stack_is_empty:
            scenario.resolve_top()


def test_agent_of_treachery_steals_any_permanent_for_the_rest_of_the_game():
    scenario = (
        Scenario()
        .player("alice", hand=["Agent of Treachery"], library=["Island"] * 5)
        .player("bob", battlefield=["Chalice of the Void"], library=["Forest"] * 5)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    chalice = scenario.find("Chalice of the Void", Zone.BATTLEFIELD, "bob")
    scenario.choose_trigger_targets("Agent of Treachery", [chalice])

    agent = scenario.put_onto_battlefield("Agent of Treachery", "alice")
    scenario.pass_until_resolved()

    assert _controller(scenario, chalice) == "alice"
    _next_turn(scenario)
    _next_turn(scenario)
    assert _controller(scenario, chalice) == "alice"
    scenario.game.destroy(agent)
    assert _controller(scenario, chalice) == "alice"  # no "for as long as"


def test_a_stolen_permanent_that_changes_zones_returns_to_its_owner():
    """CR 400.7: blinked or bounced and replayed, it is a new object."""
    scenario = (
        Scenario()
        .player("alice", hand=["Agent of Treachery"], library=["Island"] * 5)
        .player("bob", battlefield=["Grizzly Bears"], library=["Forest"] * 5)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "bob")
    scenario.choose_trigger_targets("Agent of Treachery", [bears])
    scenario.put_onto_battlefield("Agent of Treachery", "alice")
    scenario.pass_until_resolved()
    assert _controller(scenario, bears) == "alice"

    scenario.game.exile_permanent(bears)
    returned = scenario.game.put_onto_battlefield(bears, "bob")

    assert _controller(scenario, returned) == "bob"


def test_keiga_dying_steals_a_creature():
    scenario = (
        Scenario()
        .player("alice", battlefield=["Keiga, the Tide Star"], library=["Island"] * 5)
        .player("bob", battlefield=["Grizzly Bears"], library=["Forest"] * 5)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    keiga = scenario.creature("Keiga, the Tide Star", "alice")
    bears = scenario.creature("Grizzly Bears", "bob")
    scenario.choose_trigger_targets("Keiga, the Tide Star", [bears])

    scenario.game.destroy(keiga)
    scenario.pass_until_resolved()

    assert keiga.zone is Zone.GRAVEYARD
    assert _controller(scenario, bears) == "alice"
    _next_turn(scenario)
    assert _controller(scenario, bears) == "alice"
