"""Scenario: "Spells you control can't be countered this turn." (Veil of
Summer) and "Other spells you control can't be countered this turn."
(Determined, the back half of Bound // Determined) - a per-turn CR 611.2c
rules-modifying effect, as opposed to `test_cant_be_countered.py`'s printed
"This spell can't be countered" static on a single object.

`test_cant_be_countered.py` already covers CR 113.6g's printed shape
(Supreme Verdict). This file is the *different* mechanism CR 611.2c's second
sentence describes: "A continuous effect generated by the resolution of a
spell or ability that doesn't modify the characteristics or change the
controller of any objects modifies the rules of the game, so it can affect
objects that weren't affected when that continuous effect began" - which is
why the grant covers a spell already on the stack *and* one cast later the
same turn, not only spells that existed the instant Veil resolved.

`Game.counter` is where this is enforced (`machines.casting_restrictions.
spell_protected_from_countering`, consulted alongside the printed
`cannot_be_countered` - CR 101.2 gives either "can't" the same precedence).
It is recorded on `Game.casting_rule_effects`, the same list Ranger-Captain
of Eos's noncreature restriction and Teferi's sorcery-speed-flash grant
already live on, and expires through that list's own existing "until end of
turn" cleanup filter (`Game.cleanup_step`) - this file does not touch
cleanup itself.

Every CR number here was looked up with `mise run rules:find` in the session
that wrote this file: CR 611.2c, CR 101.2, CR 113.6g, CR 701.6a, CR 405.1.
"""

from magic_cards_model.machines import Step
from magic_cards_model.machines.casting_restrictions import (
    create_spells_cant_be_countered_grant,
    spell_protected_from_countering,
)
from magic_cards_model.models import Zone
from magic_cards_model.models.card_state import Counter
from tests.scenarios.harness import Scenario


def _board(*, alice_hand: list[str], bob_hand: list[str]) -> Scenario:
    return (
        Scenario()
        .player(
            "alice",
            hand=alice_hand,
            battlefield=["Forest", "Forest", "Island", "Island", "Walking Ballista"],
            library=["Forest"] * 5,
        )
        .player(
            "bob",
            hand=bob_hand,
            battlefield=["Island", "Island", "Island", "Island"],
            library=["Island"] * 5,
        )
        .build()
    )


def _give_bob_priority(scenario: Scenario) -> None:
    """Whoever just acted (the active player, Alice, by default at the start
    of her own main phase) keeps priority (CR 117.3c) - a scenario that
    wants Bob to respond has to hand it to him explicitly."""
    scenario.pass_priority("alice")


# -- (c) a spell already on the stack, and one cast later the same turn -----


def test_a_counterspell_fails_against_your_spell_already_on_the_stack():
    """Alice puts Opt on the stack, then casts Veil of Summer in response.
    Veil resolves first (CR 608.1, last in first out) and its grant already
    covers Opt, which was on the stack *before* the grant existed - CR
    611.2c's "spells you control" is not a fixed set the way a
    characteristic-modifying effect's would be."""
    scenario = _board(alice_hand=["Opt", "Veil of Summer"], bob_hand=["Counterspell"])
    scenario.start_at(Step.PRECOMBAT_MAIN)

    (island,) = scenario.untapped_sources("Island", username="alice")
    scenario.cast_onto_stack("Opt", island, username="alice")
    opt = scenario.stack_names()[-1]
    assert opt == "Opt"
    opt_state = scenario.find("Opt", Zone.STACK)

    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_onto_stack("Veil of Summer", forest, username="alice")
    scenario.resolve_top()  # Veil resolves, grants the protection

    _give_bob_priority(scenario)
    islands = scenario.untapped_sources("Island", "Island", username="bob")
    scenario.cast_onto_stack("Counterspell", *islands, username="bob", targets=[opt_state])
    scenario.resolve_top()  # the counterspell itself resolves and fails

    assert opt_state.zone is Zone.STACK, "still on the stack - not countered"
    scenario.resolve_top()  # Opt now resolves normally
    assert opt_state.zone is Zone.GRAVEYARD


def test_a_counterspell_fails_against_a_spell_you_cast_later_that_turn():
    """Veil resolves with nothing else on the stack; a second spell Alice
    casts afterward, in the same turn, is still covered - CR 611.2c's
    second sentence is exactly what makes this possible for a rules-
    modifying effect (as against `test_cant_be_countered.py`'s printed
    per-object ability, which could never reach an object that did not
    exist yet)."""
    scenario = _board(alice_hand=["Veil of Summer", "Opt"], bob_hand=["Counterspell"])
    scenario.start_at(Step.PRECOMBAT_MAIN)
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Veil of Summer", forest, username="alice")

    (island,) = scenario.untapped_sources("Island", username="alice")
    scenario.cast_onto_stack("Opt", island, username="alice")
    opt_state = scenario.find("Opt", Zone.STACK)

    _give_bob_priority(scenario)
    islands = scenario.untapped_sources("Island", "Island", username="bob")
    scenario.cast_onto_stack("Counterspell", *islands, username="bob", targets=[opt_state])
    scenario.resolve_top()

    assert opt_state.zone is Zone.STACK
    scenario.resolve_top()
    assert opt_state.zone is Zone.GRAVEYARD


# -- (d) the grant's edges: whose spells, what kind of object, how long -----


def test_an_opponents_spell_stays_counterable():
    """ "Spells you control" (Veil's controller, Alice) never covers Bob's
    own spell - the grant is per-controller, not a blanket "can't be
    countered" over every spell on the stack."""
    scenario = _board(alice_hand=["Veil of Summer", "Counterspell"], bob_hand=["Opt"])
    scenario.start_at(Step.PRECOMBAT_MAIN)
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Veil of Summer", forest, username="alice")

    _give_bob_priority(scenario)
    (island,) = scenario.untapped_sources("Island", username="bob")
    scenario.cast_onto_stack("Opt", island, username="bob")
    opt_state = scenario.find("Opt", Zone.STACK)

    scenario.pass_priority("bob")
    islands = scenario.untapped_sources("Island", "Island", username="alice")
    scenario.cast_and_resolve("Counterspell", *islands, username="alice", targets=[opt_state])

    assert opt_state.zone is Zone.GRAVEYARD, "countered normally - not Alice's own spell"


def test_an_ability_alice_controls_is_not_protected():
    """CR 405.1: "an ability ... goes on top of the stack without any card
    associated with it" - `cannot_be_countered`'s own convention (an object
    with a `.card`) is what `spell_protected_from_countering` follows too,
    so Veil's "spells you control" grant, read literally, never reaches an
    activated ability Alice controls."""
    scenario = _board(alice_hand=["Veil of Summer"], bob_hand=[])
    # CR 704.5f: a 0-toughness creature is a state-based action, and Walking
    # Ballista's printed toughness is its own +1/+1 counter count - given one
    # before anything checks state-based actions, so it survives Veil's own
    # resolution to have an ability worth activating.
    ballista = scenario.creature("Walking Ballista", "alice")
    ballista.add_counters(Counter.PLUS_ONE, 1)

    scenario.start_at(Step.PRECOMBAT_MAIN)
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Veil of Summer", forest, username="alice")

    ability = scenario.activate(ballista, index=1, targets=["bob"])
    assert ability is not None

    assert spell_protected_from_countering(scenario.game, ability) is False
    countered = scenario.game.counter(ability)
    assert countered not in scenario.game.stack, "an ability is removable despite the grant"


def test_next_turn_your_spells_are_counterable_again():
    """CR 514.2 / `Game.cleanup_step`'s own existing "until end of turn"
    filter over `casting_rule_effects` - not edited by this file - is what
    ends the grant; this only proves that filter actually reaches the new
    row."""
    scenario = _board(alice_hand=["Veil of Summer", "Opt"], bob_hand=["Counterspell"])
    scenario.start_at(Step.PRECOMBAT_MAIN)
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Veil of Summer", forest, username="alice")

    scenario.start_at(Step.CLEANUP)
    scenario.turn_based_actions()  # CR 514.2: "until end of turn" effects end
    scenario.advance()  # crosses into the next turn (bob's, CR 103.4)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    scenario.pass_priority("bob")
    (island,) = scenario.untapped_sources("Island", username="alice")
    scenario.cast_onto_stack("Opt", island, username="alice")
    opt_state = scenario.find("Opt", Zone.STACK)

    scenario.pass_priority("alice")
    islands = scenario.untapped_sources("Island", "Island", username="bob")
    scenario.cast_and_resolve("Counterspell", *islands, username="bob", targets=[opt_state])

    assert opt_state.zone is Zone.GRAVEYARD, "the grant is gone - an ordinary counter"


# -- (e) Determined: OTHER spells, never Determined itself -------------------


def test_determined_protects_a_later_spell_but_not_itself():
    """Determined's own printed word: "**Other** spells you control can't be
    countered this turn." Bound // Determined's front half, Bound, needs a
    creature to sacrifice and is not what this test is about - Determined
    is cast directly via `cast_as_split_half` (CR 709.3), the same way
    `test_split_cards.py` chooses a split card's back half."""
    scenario = _board(alice_hand=["Bound // Determined", "Opt"], bob_hand=["Counterspell"])
    scenario.start_at(Step.PRECOMBAT_MAIN)

    casting = scenario.cast("Bound", username="alice")
    casting.cast_as_split_half("Determined")
    payment = casting.begin_paying()
    forest, island = scenario.untapped_sources("Forest", "Island", username="alice")
    scenario.pay_with(payment, forest, island)
    scenario.put_on_stack(casting)
    scenario.resolve_top()

    (island,) = scenario.untapped_sources("Island", username="alice")
    scenario.cast_onto_stack("Opt", island, username="alice")
    opt_state = scenario.find("Opt", Zone.STACK)

    scenario.pass_priority("alice")
    islands = scenario.untapped_sources("Island", "Island", username="bob")
    scenario.cast_onto_stack("Counterspell", *islands, username="bob", targets=[opt_state])
    scenario.resolve_top()

    assert opt_state.zone is Zone.STACK, "Opt is an *other* spell - protected"


def test_determined_does_not_exclude_a_second_spells_own_protection():
    """The exclusion is by identity (`excluded_source_id`), not by controller
    or by "the first spell this grant was checked against" - a *different*
    spell than the one named as excluded is still covered, read directly off
    `spell_protected_from_countering` the same way `test_cant_be_countered.py`
    reads `cannot_be_countered` directly (CR 109.4: only an object on the
    stack or battlefield has a controller at all, so both spells here are put
    on the stack rather than read straight out of hand).

    In a real game, Determined itself is never actually reachable through
    this exclusion: by the time its own grant exists (its resolution just
    created it), Determined has already left the stack (CR 601.2i put it
    there; resolving is what takes it off), so nothing could legally hand it
    to `Game.counter` at all. `excluded_source_id` still has to name
    *something* real for a card printed with "Other", and this is the
    direct proof that naming it excludes only that one object, by id, and
    nothing else with the same controller.
    """
    scenario = _board(alice_hand=["Bound // Determined", "Opt"], bob_hand=[])
    scenario.start_at(Step.PRECOMBAT_MAIN)

    casting = scenario.cast("Bound", username="alice")
    casting.cast_as_split_half("Determined")
    payment = casting.begin_paying()
    forest, island = scenario.untapped_sources("Forest", "Island", username="alice")
    scenario.pay_with(payment, forest, island)
    determined = scenario.put_on_stack(casting)

    (other_island,) = scenario.untapped_sources("Island", username="alice")
    scenario.cast_onto_stack("Opt", other_island, username="alice")
    opt = scenario.find("Opt", Zone.STACK)

    # The grant would ordinarily be minted inside `resolve_top`'s own
    # `_id_allocator_scope` (Determined's own effect appends it there) - this
    # test builds the row by hand instead, so it opens the identical scope
    # itself, the same way `test_continuous_effects_with_a_duration.py`
    # already does for a hand-built `ContinuousEffect`: an id minted outside
    # any scope falls back to a random `uuid4()` (see `ids.py`), which would
    # replay to a *different* id on the second run and fail the round-trip
    # invariant every scenario test gets for free.
    with scenario.game._id_allocator_scope():  # noqa: SLF001
        scenario.game.casting_rule_effects.append(
            create_spells_cant_be_countered_grant(
                "alice", "Determined", excluded_source_id=determined.id
            )
        )

    assert spell_protected_from_countering(scenario.game, determined) is False
    assert spell_protected_from_countering(scenario.game, opt) is True
