def test_the_trigger_resolves_after_its_creature_dies_and_pumps_nothing():
    """CR 113.7a: the ability outlives its source, and finds nothing to affect.

    Alice's Bolt triggers prowess; Bob Bolts the Swiftspear in response, which
    dies to the lethal-damage state-based action (CR 704.5g) before the trigger
    resolves. CR 611.2c fixes the set of objects a resolving effect applies to
    when it is created, and by then the creature is gone.
    """
    scenario = board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    scenario.pass_priority("alice")
    scenario.cast_onto_stack(
        "Lightning Bolt",
        *scenario.untapped_sources("Mountain", username="bob"),
        username="bob",
        targets=[swiftspear],
    )
    while scenario.stack_names():
        scenario.resolve_top()
        scenario.state_based_actions()

    assert swiftspear.zone is Zone.GRAVEYARD
    assert [
        effect
        for effect in scenario.game.continuous_effects.active(scenario.game)
        if effect.source_id == swiftspear.id
    ] == []
