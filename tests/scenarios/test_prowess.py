def test_prowess_makes_the_creature_bigger_until_end_of_turn():
    """CR 702.108a's effect half, applied by the game rather than by the test."""
    scenario = board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")
    assert (swiftspear.power, swiftspear.toughness) == (1, 2)

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    scenario.resolve_top()  # the prowess trigger

    assert scenario.game.power_of(swiftspear) == 1 + prowess_bonus[0]
    assert scenario.game.toughness_of(swiftspear) == 2 + prowess_bonus[1]


def test_the_pump_ends_in_the_cleanup_step_and_not_at_the_end_step():
    """CR 500.5b sends "until end of turn" to CR 514.2, which is cleanup.

    A creature pumped during the end step is still pumped when the end step is
    over; the effect ends in the cleanup step, at the same moment marked damage
    is wiped (CR 703.4p).
    """
    scenario = board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    scenario.resolve_top()
    assert scenario.game.power_of(swiftspear) == 2

    scenario.start_at(Step.END_STEP)
    assert scenario.game.power_of(swiftspear) == 2  # still pumped

    scenario.game.cleanup_step()
    assert scenario.game.power_of(swiftspear) == 1


def test_two_noncreature_spells_in_one_turn_stack_two_pumps():
    """CR 611.2a: each resolution generates its own effect, and both last.

    Nothing in CR 702.108a makes the pump a once-per-turn or a replace-the-last
    one: two Bolts are two casts, two triggers (CR 603.2), and two sublayer 7c
    effects (CR 613.4c) applied in timestamp order (CR 613.7b) on top of each
    other.
    """
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Lightning Bolt", "Lightning Bolt"],
            battlefield=["Monastery Swiftspear", "Mountain", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")
    first, second = scenario.untapped_sources("Mountain", "Mountain")

    scenario.cast_onto_stack("Lightning Bolt", first, targets=["bob"])
    while scenario.stack_names():
        scenario.resolve_top()
    assert (scenario.game.power_of(swiftspear), scenario.game.toughness_of(swiftspear)) == (2, 3)

    scenario.cast_onto_stack("Lightning Bolt", second, targets=["bob"])
    while scenario.stack_names():
        scenario.resolve_top()
    assert (scenario.game.power_of(swiftspear), scenario.game.toughness_of(swiftspear)) == (3, 4)


def test_two_prowess_creatures_each_get_their_own_trigger():
    """CR 702.108a is an ability of each creature, so one cast triggers both."""
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Lightning Bolt"],
            battlefield=["Monastery Swiftspear", "Monastery Swiftspear", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    one, other = scenario.creatures("Monastery Swiftspear", "Monastery Swiftspear")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    assert scenario.stack_names() == [
        "Lightning Bolt",
        "Monastery Swiftspear's triggered ability",
        "Monastery Swiftspear's triggered ability",
    ]
    while scenario.stack_names():
        scenario.resolve_top()

    assert scenario.game.power_of(one) == 2
    assert scenario.game.power_of(other) == 2


def test_the_pump_is_gone_by_the_opponents_turn():
    """CR 514.2 / 703.4p, reached by the turn driving itself rather than by hand.

    `test_the_pump_ends_in_the_cleanup_step_and_not_at_the_end_step` calls
    `cleanup_step` directly; this one advances step by step with the CR 703.4
    turn-based actions on, so the cleanup that ends the effect is the one the
    turn machine performs.
    """
    scenario = (
        Scenario()
        .automatic_turn_based_actions()
        .player(
            "alice",
            hand=["Lightning Bolt"],
            library=["Forest"] * 10,
            battlefield=["Monastery Swiftspear", "Mountain"],
        )
        .player("bob", library=["Forest"] * 10)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    while scenario.stack_names():
        scenario.resolve_top()
    assert scenario.game.power_of(swiftspear) == 2

    while scenario.step is not Step.UPKEEP:
        scenario.advance()

    assert scenario.game.power_of(swiftspear) == 1
    assert scenario.game.toughness_of(swiftspear) == 2


def test_the_pump_is_the_power_combat_damage_is_dealt_with():
    """CR 510.1a, 120.2a: an attacker assigns damage equal to *its* power.

    The pump is a layer 7c effect rather than anything written on the card, so
    this is the assertion that says the layers are what combat reads.
    """
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Lightning Bolt"],
            battlefield=["Monastery Swiftspear", "Mountain"],
        )
        .player("bob", life=20)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    while scenario.stack_names():
        scenario.resolve_top()

    scenario.start_at(Step.DECLARE_ATTACKERS)
    scenario.attack_with(swiftspear, defending="bob")
    scenario.no_blocks()
    (assignment,) = scenario.combat_damage()
    target, amount = assignment

    assert amount == 2  # 1 printed + 1 prowess, not the printed 1
    assert target.life == 20 - 3 - 2  # the Bolt to the face, then the attack


def test_the_pump_keeps_the_creature_alive_through_otherwise_lethal_damage():
    """CR 704.5g reads the *current* toughness, so 2 damage is not lethal at 3.

    A 1/2 Monastery Swiftspear blocked by a 2/2 dies (CR 302.7); pumped to 2/3
    by one prowess trigger it survives, and the 2/2 does not.
    """
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Lightning Bolt"],
            battlefield=["Monastery Swiftspear", "Mountain"],
        )
        .player("bob", battlefield=["Grizzly Bears"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    swiftspear = scenario.creature("Monastery Swiftspear")
    bears = scenario.creature("Grizzly Bears", "bob")

    scenario.cast_onto_stack(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    while scenario.stack_names():
        scenario.resolve_top()

    scenario.start_at(Step.DECLARE_ATTACKERS)
    scenario.attack_with(swiftspear, defending="bob")
    scenario.block(swiftspear, bears)
    scenario.combat_damage()
    scenario.state_based_actions()

    assert swiftspear.zone is Zone.BATTLEFIELD
    assert bears.zone is Zone.GRAVEYARD


