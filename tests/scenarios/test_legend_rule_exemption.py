"""Scenario: FRA S9's legend-rule exemption - "The 'legend rule' doesn't
apply to permanents you control [this turn]." - and the deeper interaction
bug it exposed.

- **Mirror Box** and **Sakashima of a Thousand Faces** (off-set, two real and
  unrelated cards) both print the plain CR 611.3 static shape: "The 'legend
  rule' doesn't apply to permanents you control." - present for as long as
  the permanent has the ability (CR 604.2), checked once, board-wide, by
  `Game._legend_rule_losers`.
- **Hall of Echoes** (Reality Fracture), "{5}: This land becomes a copy of
  target creature you control until end of turn. The 'legend rule' doesn't
  apply to permanents you control this turn." - the fra-survey misread
  ("only the copy half reaches create_continuous_effect_of_ability"). The
  gap went deeper than a missing parser: once both sentences *were* read,
  the grant still silently vanished, because CR 613.6's "already started
  applying" tracking (`_still_exists`, keyed by `(source_id, source_ability)`)
  treats the "becomes a copy" sentence and the legend-rule sentence as two
  *unrelated* effects - and the copy sentence overwrites the source's own
  abilities in layer 1 before layer 6 ever asks whether the legend-rule
  sentence's printed line is still there to grant it from. Both sentences
  are one CR 608.2c instruction, resolved together at the same moment
  (CR 611.2c), so `parsed_layer_effects`'s `combined` now re-keys every
  effect from the same source onto the "becomes a copy" effect's own key
  once one is present - the one whose text layer 1 is about to erase - so
  they all count as started together.

The rules these rest on:

- **CR 704.5j** - "If two or more legendary permanents with the same name
  are controlled by the same player, that player chooses one of them, and
  the rest are put into their owners' graveyards" - what the exemption
  refuses to run at all for an exempt player.
- **CR 604.2** - a static ability's effect is active "as long as the
  permanent with the ability remains on the battlefield and has the
  ability" - Mirror Box's and Sakashima's own duration.
- **CR 611.2** / **CR 611.2a** - a resolving ability's continuous effect
  "lasts as long as stated ... (such as 'until end of turn')" - Hall of
  Echoes' own "this turn".
- **CR 613.6** - "Some continuous effects are generated by ... a static
  ability that has since left the battlefield or lost the ability. Such
  effects continue if they had already started to apply" - the rule whose
  bookkeeping this file's second bug was in.

Every CR number here was looked up with `knowledge_search(q="...",
type="rules")` in the session that wrote it, and every card's text with
`resolve_cards` or straight off its fixture.
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone
from tests.scenarios.harness import Scenario


def test_mirror_box_keeps_both_legendary_copies_off_set():
    """Off-set proof: a real, well-known card, the plain permanent-static
    shape with no "this turn" at all."""
    scenario = (
        Scenario()
        .player("alice", battlefield=["Mirror Box", "Questing Beast", "Questing Beast"])
        .build()
    )
    scenario.game.check_state_based_actions()

    assert scenario.battlefield_names().count("Questing Beast") == 2


def test_sakashima_of_a_thousand_faces_keeps_both_legendary_copies_off_set():
    """Off-set proof: a second, unrelated real card with the identical
    permanent-static sentence."""
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=["Sakashima of a Thousand Faces", "Questing Beast", "Questing Beast"],
        )
        .build()
    )
    scenario.game.check_state_based_actions()

    assert scenario.battlefield_names().count("Questing Beast") == 2


def test_a_double_legend_still_loses_one_copy_with_no_exemption_at_all():
    """Control: nothing here changes the ordinary CR 704.5j check."""
    scenario = Scenario().player("alice", battlefield=["Questing Beast", "Questing Beast"]).build()
    scenario.game.check_state_based_actions()

    assert scenario.battlefield_names().count("Questing Beast") == 1


def test_hall_of_echoes_exempts_the_legend_rule_after_it_becomes_a_copy():
    """The main case: Hall of Echoes' own `{5}` ability copies a legendary
    creature the controller already has one of, and both must survive."""
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            battlefield=[
                "Hall of Echoes",
                "Karn, Argent Defender",
                "Forest",
                "Forest",
                "Forest",
                "Forest",
                "Forest",
            ],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    hall = scenario.find("Hall of Echoes", Zone.BATTLEFIELD, "alice")
    karn = scenario.find("Karn, Argent Defender", Zone.BATTLEFIELD, "alice")
    sources = scenario.untapped_sources(
        "Forest", "Forest", "Forest", "Forest", "Forest", username="alice"
    )

    scenario.activate(hall, *sources, index=1, username="alice", targets=[karn])
    scenario.resolve_top()
    scenario.game.check_state_based_actions()

    assert hall.zone is Zone.BATTLEFIELD
    assert karn.zone is Zone.BATTLEFIELD
    assert scenario.game.characteristics_of(hall).name == "Karn, Argent Defender"


def test_hall_of_echoes_activation_logs_no_spurious_layer_remainder_notice():
    """fra-final-audit batch A, item 3: the grant works (the tests above),
    but the ability's own "this turn" legend-rule sentence used to be
    misclassified as an unread sibling of the "becomes a copy" sentence -
    `_classify_resolution_layer_sentence` excluded *any* sentence matching
    `_parse_static_layer_sentence` from "genuine", which is right for a
    permanent's own forever CR 611.3 static line (an anthem, Mirror Box's own
    plain exemption) and wrong for the CR 611.2 one-shot "this turn" variant,
    which only ever appears embedded in a resolving ability's own text and is
    genuinely read by that same fallback. `_compose_layer_effect_with_
    remainder_for_ability` then logged a `LayerRemainderNotice` for a
    sentence `create_continuous_effect_of_ability` had already applied.
    """
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            battlefield=[
                "Hall of Echoes",
                "Grizzly Bears",
                "Forest",
                "Forest",
                "Forest",
                "Forest",
                "Forest",
            ],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    hall = scenario.find("Hall of Echoes", Zone.BATTLEFIELD, "alice")
    bears = scenario.creature("Grizzly Bears", "alice")
    sources = scenario.untapped_sources(
        "Forest", "Forest", "Forest", "Forest", "Forest", username="alice"
    )

    scenario.activate(hall, *sources, index=1, username="alice", targets=[bears])
    scenario.resolve_top()

    assert scenario.game.layer_remainder_notices == []


