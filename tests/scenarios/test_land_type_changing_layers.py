"""Scenario: land-type-changing effects meeting each other in layer 4.

Four printings whose whole text is a board-wide land-type change, and what
happens when two of them are out at once. All four are static abilities
(CR 604.2) generating continuous effects in **layer 4** (CR 613.1d, "Type-
changing effects are applied"), so the only question the rules leave is the
order *within* that layer - which is exactly what this file is about.

Card text, every line verified with `resolve_cards` in the session that wrote
this file:

- **Blood Moon** (Enchantment): "Nonbasic lands are Mountains."
- **Urborg, Tomb of Yawgmoth** (Legendary Land): "Each land is a Swamp in
  addition to its other land types."
- **Yavimaya, Cradle of Growth** (Legendary Land): "Each land is a Forest in
  addition to its other land types."
- **Dryad of the Ilysian Grove** (Enchantment Creature): "You may play an
  additional land on each of your turns. / Lands you control are every basic
  land type in addition to their other types."

Note the two different subjects, which this file pins separately: Urborg and
Yavimaya say "**Each** land", so they reach both players' lands, while Dryad
says "Lands **you control**" and reaches only its controller's.

Every CR number below was looked up with `knowledge_search(q="...",
type="rules")` in the session that wrote this file:

- **CR 613.1d** - "Layer 4: Type-changing effects are applied." All four
  effects here live in this one layer, which is what makes ordering the whole
  question.
- **CR 613.3** - "Within layers 2-6, apply effects from characteristic-
  defining abilities first, then all other effects in timestamp order ... Note
  that dependency may alter the order in which effects are applied."
- **CR 613.7** - "Within a layer or sublayer, determining which order effects
  are applied in is *usually* done using a timestamp system."
- **CR 613.7a** - "A continuous effect generated by a static ability has the
  same timestamp as the object the static ability is on", which is why the
  order permanents reach the battlefield is the order their effects apply in.
- **CR 613.8** - "If a dependency exists, it will override the timestamp
  system."
- **CR 613.8a** - an effect depends on another if "(b) applying the other
  would change the text or the existence of this effect, what it does to any
  objects, or which objects it applies to".
- **CR 613.8b** - "An effect dependent on one or more other effects waits to
  apply until just after all of those effects have been applied."
- **CR 613.6** - an effect that has already started applying keeps applying
  even once the ability generating it is gone; one that has not started and
  whose ability has been removed never applies at all.
- **CR 305.7** - "If an effect sets a land's subtype to one or more of the
  basic land types, the land no longer has its old land type. It loses all
  abilities generated from its rules text, its old land types, and any..."
  **`knowledge_search` truncates this rule at "and any" on every phrasing
  tried in this session**, so the tail is deliberately not quoted or relied on
  anywhere here. Everything asserted below rests only on the part that does
  come back: the old land type goes, and the rules-text abilities go with it.
- **CR 205.1b** - the "in addition to" form: an object that gains a type but
  "retains a prior card type" keeps everything it had. Urborg, Yavimaya and
  Dryad are all this shape, which is why none of them is a CR 305.7 setting
  effect.
- **CR 305.6** - "An object with the land card type and a basic land type has
  the intrinsic ability '{T}: Add [mana symbol]'", so a type gained brings its
  mana ability with it.
- **CR 205.4c / CR 305.8** - "Any land that doesn't have this supertype is a
  nonbasic land, **even if it has a basic land type**." This is the rule that
  decides the dependency questions below: nothing any of these effects does
  can change whether a land is nonbasic.

## The two orderings, and why they differ

The headline of this file is that the two pairs answer the ordering question
by *different halves of rule 613*, and the engine has to reach both through
the same generic machinery:

- **Urborg (or Yavimaya) against Blood Moon is decided by dependency, and the
  two orders give the same answer.** Blood Moon applying makes Urborg a
  Mountain and, by CR 305.7, strips the rules-text ability generating Urborg's
  own effect - so applying Blood Moon changes *the existence of* Urborg's
  effect, which is CR 613.8a clause (b) exactly. Urborg therefore depends on
  Blood Moon. The reverse is not true: Urborg adds the Swamp subtype, and
  CR 205.4c/305.8 make "nonbasic" a supertype question that a subtype cannot
  answer differently, so Blood Moon's subject set and what it writes are
  untouched. One-way dependency, so CR 613.8b makes Blood Moon apply first
  **regardless of timestamp**, and Urborg's effect never applies at all
  (CR 613.6). Nothing is ever a Swamp.
- **Dryad against Blood Moon is decided by timestamps, and the two orders give
  different answers.** Neither changes the other's text, existence, or subject
  set - "nonbasic" is again a supertype question - and Dryad does the same
  thing to a land either way: it ends up with all five basic land types. So
  CR 613.8 finds no dependency and CR 613.7 decides. Blood Moon last leaves a
  nonbasic land a Mountain and nothing else; Dryad last leaves it all five.

That second pair is the one that proves the ordering is genuinely generic
rather than a hardcoded answer per card pair: nothing about it can be right by
accident, because the same two cards must produce two different boards.
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Color, Zone
from tests.scenarios.harness import Scenario


def _board(*names, opponent=()):
    """A battlefield in a stated order. CR 613.7a gives each static ability's
    effect the timestamp of the permanent it is on, and `Scenario` stamps them
    in the order listed, so the argument order *is* the timestamp order."""
    scenario = (
        Scenario()
        .player("alice", battlefield=list(names))
        .player("bob", battlefield=list(opponent))
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


def _subtypes(scenario, name, username="alice"):
    """One permanent's *computed* subtypes (CR 613.5), as a set - order within
    the type line is not a characteristic and nothing here asserts on it."""
    permanent = next(
        state
        for state in scenario.game.battlefield
        if state.name == name and state.controller == username
    )
    return set(scenario.game.characteristics_of(permanent).subtypes)


def _abilities(scenario, name, username="alice"):
    permanent = next(
        state
        for state in scenario.game.battlefield
        if state.name == name and state.controller == username
    )
    return set(scenario.game.characteristics_of(permanent).abilities)


# --------------------------------------------------------------------------
# The four effects on their own
# --------------------------------------------------------------------------


def test_blood_moon_sets_a_nonbasic_land_to_mountain_and_strips_its_text():
    """CR 305.7's setting form: the old land type goes, and the abilities the
    land's rules text generated go with it. Ancient Tomb's own "{T}: Add
    {C}{C}" is gone and only the Mountain's intrinsic {R} (CR 305.6) is left.
    """
    scenario = _board("Blood Moon", "Ancient Tomb")

    assert _subtypes(scenario, "Ancient Tomb") == {"Mountain"}
    assert _abilities(scenario, "Ancient Tomb") == {"{T}: Add {R}."}


def test_blood_moon_leaves_a_basic_land_alone():
    """CR 205.4c, CR 305.8: "nonbasic" is the *supertype* question. A Forest
    has the basic supertype, so Blood Moon never sees it."""
    scenario = _board("Blood Moon", "Forest")

    assert _subtypes(scenario, "Forest") == {"Forest"}


def test_urborg_makes_every_land_a_swamp_in_addition():
    """CR 205.1b's additive form - the Forest is still a Forest - and CR 305.6
    hands over the {B} that comes with the Swamp type."""
    scenario = _board("Urborg, Tomb of Yawgmoth", "Forest")

    assert _subtypes(scenario, "Forest") == {"Forest", "Swamp"}
    # A basic land's own mana ability is printed as reminder text (CR 207.2,
    # "({T}: Add {G}.)"), so the Swamp's freshly granted line is the one
    # spelled bare - and the printed one is still there beside it.
    assert "{T}: Add {B}." in _abilities(scenario, "Forest")
    assert "({T}: Add {G}.)" in _abilities(scenario, "Forest")


def test_yavimaya_makes_every_land_a_forest_in_addition():
    """Urborg's sentence with a different basic land type, read off the text
    rather than the card name."""
    scenario = _board("Yavimaya, Cradle of Growth", "Island")

    assert _subtypes(scenario, "Island") == {"Island", "Forest"}
    assert "{T}: Add {G}." in _abilities(scenario, "Island")
    assert "({T}: Add {U}.)" in _abilities(scenario, "Island")


def test_urborg_reaches_an_opponents_lands_because_it_says_each_land():
    """ "**Each** land is a Swamp" - not "lands you control". Bob's Island is
    Urborg's business even though Alice controls Urborg."""
    scenario = _board("Urborg, Tomb of Yawgmoth", opponent=["Island"])

    assert _subtypes(scenario, "Island", "bob") == {"Island", "Swamp"}


def test_dryad_reaches_only_its_controllers_lands():
    """Dryad says "Lands **you control**", so the same board that Urborg
    changes for both players changes for one. This is the distinction the
    previous test is the other half of."""
    scenario = _board("Dryad of the Ilysian Grove", "Island", opponent=["Island"])

    assert _subtypes(scenario, "Island") == {"Plains", "Island", "Swamp", "Mountain", "Forest"}
    assert _subtypes(scenario, "Island", "bob") == {"Island"}


def test_dryad_does_not_make_itself_a_land():
    """ "Lands you control" is a condition on the object, and Dryad of the
    Ilysian Grove is an Enchantment Creature - Nymph Dryad, not a land. Its own
    subtypes are untouched."""
    scenario = _board("Dryad of the Ilysian Grove", "Island")

    assert _subtypes(scenario, "Dryad of the Ilysian Grove") == {"Nymph", "Dryad"}


# --------------------------------------------------------------------------
# CR 613.8: Urborg / Yavimaya against Blood Moon, both orders
# --------------------------------------------------------------------------


def test_urborg_before_blood_moon_still_leaves_nothing_a_swamp():
    """Urborg has the *earlier* timestamp, and still loses.

    CR 613.8's dependency overrides CR 613.7's timestamps: applying Blood Moon
    strips the ability generating Urborg's effect (CR 305.7), which changes the
    *existence* of that effect - CR 613.8a clause (b). So Urborg's effect
    depends on Blood Moon's, waits for it (CR 613.8b), and by the time it would
    apply its own ability is gone and it never applies at all (CR 613.6).
    """
    scenario = _board("Urborg, Tomb of Yawgmoth", "Blood Moon", "Ancient Tomb")

    assert _subtypes(scenario, "Urborg, Tomb of Yawgmoth") == {"Mountain"}
    assert _subtypes(scenario, "Ancient Tomb") == {"Mountain"}
    assert "Swamp" not in _subtypes(scenario, "Ancient Tomb")


def test_blood_moon_before_urborg_gives_the_identical_board():
    """The other order, and the point of the pair: the answer does not move.

    A dependency is not a tiebreak - it *replaces* the timestamp question, so
    reversing the timestamps changes nothing. If this test and the one above
    ever disagree, the engine has started deciding this pair by timestamp.
    """
    scenario = _board("Blood Moon", "Urborg, Tomb of Yawgmoth", "Ancient Tomb")

    assert _subtypes(scenario, "Urborg, Tomb of Yawgmoth") == {"Mountain"}
    assert _subtypes(scenario, "Ancient Tomb") == {"Mountain"}
    assert "Swamp" not in _subtypes(scenario, "Ancient Tomb")


def test_yavimaya_against_blood_moon_answers_the_same_way_in_both_orders():
    """Yavimaya is Urborg's sentence with a different type, so it must reach
    the identical dependency - which is a claim about the *machinery* reading
    the sentence, not about either card's name."""
    forward = _board("Yavimaya, Cradle of Growth", "Blood Moon", "Ancient Tomb")
    backward = _board("Blood Moon", "Yavimaya, Cradle of Growth", "Ancient Tomb")

    for scenario in (forward, backward):
        assert _subtypes(scenario, "Yavimaya, Cradle of Growth") == {"Mountain"}
        assert _subtypes(scenario, "Ancient Tomb") == {"Mountain"}
        assert "Forest" not in _subtypes(scenario, "Ancient Tomb")


def test_urborg_still_reaches_a_basic_land_under_blood_moon_by_neither_effect():
    """A basic Forest is out of Blood Moon's reach (CR 205.4c) - but Urborg's
    effect does not exist to reach it either, because Blood Moon applied first
    and removed Urborg's ability. So the Forest is left simply a Forest, which
    is not what either card on its own would have said."""
    scenario = _board("Urborg, Tomb of Yawgmoth", "Blood Moon", "Forest")

    assert _subtypes(scenario, "Forest") == {"Forest"}


# --------------------------------------------------------------------------
# CR 613.7: Dryad against Blood Moon, both orders - the timestamp pair
# --------------------------------------------------------------------------


def test_blood_moon_after_dryad_leaves_a_nonbasic_land_only_a_mountain():
    """Dryad first, Blood Moon second.

    No dependency exists in either direction - Blood Moon's "nonbasic" is a
    supertype question no subtype can change (CR 205.4c, CR 305.8), and Dryad
    ends up giving a land all five basic types whichever board it is handed -
    so CR 613.7's timestamps decide. Blood Moon has the later timestamp and its
    CR 305.7 *setting* form overwrites everything Dryad added.
    """
    scenario = _board("Dryad of the Ilysian Grove", "Blood Moon", "Ancient Tomb")

    assert _subtypes(scenario, "Ancient Tomb") == {"Mountain"}
    assert _abilities(scenario, "Ancient Tomb") == {"{T}: Add {R}."}


def test_dryad_after_blood_moon_gives_a_nonbasic_land_all_five_types():
    """The reverse order, and a genuinely different board.

    This is the test that proves the layer-4 ordering is generic. The pair is
    identical to the one above in every way except which permanent arrived
    first, and the answer changes - so the engine cannot be answering from a
    per-card-pair table, and cannot be collapsing the layer into one fixed
    order either.
    """
    scenario = _board("Blood Moon", "Dryad of the Ilysian Grove", "Ancient Tomb")

    assert _subtypes(scenario, "Ancient Tomb") == {
        "Plains",
        "Island",
        "Swamp",
        "Mountain",
        "Forest",
    }
    assert {
        "{T}: Add {W}.",
        "{T}: Add {U}.",
        "{T}: Add {B}.",
        "{T}: Add {R}.",
        "{T}: Add {G}.",
    } <= _abilities(scenario, "Ancient Tomb")


def test_the_two_dryad_orders_disagree():
    """Stated as its own assertion so the file fails loudly if the layer ever
    stops distinguishing them, rather than only failing whichever of the two
    tests above happens to be checked first."""
    dryad_first = _board("Dryad of the Ilysian Grove", "Blood Moon", "Ancient Tomb")
    moon_first = _board("Blood Moon", "Dryad of the Ilysian Grove", "Ancient Tomb")

    assert _subtypes(dryad_first, "Ancient Tomb") != _subtypes(moon_first, "Ancient Tomb")


# --------------------------------------------------------------------------
# Two additive effects together: no ordering question at all
# --------------------------------------------------------------------------


def test_dryad_and_urborg_together_split_along_who_controls_what():
    """Both are CR 205.1b additive effects that never remove anything, so they
    commute and no order matters - but their *subjects* differ, and that shows.

    Alice's land is caught by both and ends up every basic type; Bob's land is
    caught only by Urborg's "each land" and is a Swamp in addition to what it
    had. The same board, read two ways, because of two different subject
    clauses.
    """
    scenario = _board(
        "Dryad of the Ilysian Grove",
        "Urborg, Tomb of Yawgmoth",
        "Ancient Tomb",
        opponent=["Ancient Tomb"],
    )

    assert _subtypes(scenario, "Ancient Tomb") == {
        "Plains",
        "Island",
        "Swamp",
        "Mountain",
        "Forest",
    }
    assert _subtypes(scenario, "Ancient Tomb", "bob") == {"Swamp"}


def test_urborg_and_yavimaya_together_give_every_land_both_types():
    """Two additive effects in one layer, neither depending on the other, and
    the answer is the union whichever way round they are read."""
    forward = _board("Urborg, Tomb of Yawgmoth", "Yavimaya, Cradle of Growth", "Island")
    backward = _board("Yavimaya, Cradle of Growth", "Urborg, Tomb of Yawgmoth", "Island")

    for scenario in (forward, backward):
        assert _subtypes(scenario, "Island") == {"Island", "Swamp", "Forest"}


def test_urborg_makes_itself_a_swamp_too_because_it_is_a_land():
    """ "Each land" includes the Urborg saying it - it is a Legendary *Land*.
    Nothing excludes it the way an "other" clause would (CR 700.4)."""
    scenario = _board("Urborg, Tomb of Yawgmoth")

    assert "Swamp" in _subtypes(scenario, "Urborg, Tomb of Yawgmoth")


# --------------------------------------------------------------------------
# The granted type is not decoration: it can actually be tapped for
# --------------------------------------------------------------------------


def test_a_forest_under_urborg_can_actually_be_tapped_for_black():
    """CR 305.6's intrinsic ability is a real ability, not a line on a report.

    A land that gained the Swamp type gained "{T}: Add {B}" with it, and
    Urborg's whole function is that every land is a black source - so the
    ability has to be activatable, through the same `CostPayment.tap_for_mana`
    a real game pays with, and not merely visible on the computed board.
    """
    scenario = _board("Urborg, Tomb of Yawgmoth", "Forest")
    forest = scenario.find("Forest", Zone.BATTLEFIELD)

    assert Color.BLACK in scenario.game.colors_could_produce(forest)  # CR 106.7

    index = next(
        i
        for i, ability in enumerate(scenario.game.activated_abilities(forest))
        if ability.raw == "{T}: Add {B}."
    )
    payment = scenario.game.begin_activating(forest, index, "alice")
    payment.tap_for_mana(forest, [Color.BLACK])

    assert payment.pool.floating == {Color.BLACK: 1}
    assert forest.tapped


def test_a_land_under_dryad_can_be_tapped_for_any_of_the_five():
    """The same thing five times over: every basic land type gained brings its
    own mana ability, so one Wastes is a source of all five colours."""
    scenario = _board("Dryad of the Ilysian Grove", "Wastes")
    wastes = scenario.find("Wastes", Zone.BATTLEFIELD)

    assert scenario.game.colors_could_produce(wastes) >= {
        Color.WHITE,
        Color.BLUE,
        Color.BLACK,
        Color.RED,
        Color.GREEN,
    }


def test_a_land_that_leaves_stops_changing_anything():
    """CR 604.2: a static ability's continuous effect is active only "as long
    as the permanent with the ability remains on the battlefield". Urborg in
    the graveyard is not making anything a Swamp."""
    scenario = _board("Urborg, Tomb of Yawgmoth", "Island")
    assert _subtypes(scenario, "Island") == {"Island", "Swamp"}

    urborg = scenario.find("Urborg, Tomb of Yawgmoth", Zone.BATTLEFIELD)
    scenario.game.put_into_graveyard(urborg)

    assert _subtypes(scenario, "Island") == {"Island"}
