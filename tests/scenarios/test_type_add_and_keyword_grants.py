"""Scenario: "<subject> becomes a <subtype> in addition to its other types and
gains <keyword>[, <keyword>, ... and <keyword>] until end of turn." - one
resolving instruction that lands in two layers.

- **CR 613.1d** - layer 4: type-changing effects, "effects that change an
  object's card type, subtype, and/or supertype". The subtype is *added*:
- **CR 205.1b** - "in addition to its other types" retains every prior card
  type and subtype.
- **CR 205.3m** - creature types are the subtype vocabulary ("Avatar",
  "Dragon"), so the word is read as a subtype, not a card type.
- **CR 613.1f** - layer 6: ability-adding effects, one grant per keyword.
- **CR 613.7b** - a continuous effect generated by the resolution of a spell
  or ability receives a timestamp at the time it is created: both halves of
  the one instruction share it.
- **CR 611.2c** - the set of objects affected is fixed when the effect begins.
- **CR 702.11b** - hexproof: "can't be the target of spells or abilities your
  opponents control", enforced here on a real opponent's spell.

- **CR 611.2a** - with no duration stated, the effect lasts until the end of
  the game.

Enter the Avatar State is the reported card ("Until end of turn, target
creature you control becomes an Avatar ..."). Archangel Elspeth is the second
printing: a loyalty ability, an anaphoric "It" after a counter sentence rather
than a target, one keyword rather than four, and no duration at all.
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.machines.combat import Keyword, has_keyword
from magic_cards_model.machines.layers import Layer
from magic_cards_model.models import Zone
from tests.scenarios.harness import Scenario


def computed(scenario: Scenario):
    return scenario.game.continuous_effects.board(scenario.game.battlefield)


def notices(scenario: Scenario) -> list[object]:
    """Every fail-closed notice the game recorded - a spell that half-ran
    would leave one of these behind."""
    game = scenario.game
    found: list[object] = list(game.continuous_effects.layer_notices)
    for name in type(game).model_fields:
        if name.endswith("_notices"):
            found.extend(getattr(game, name))
    return found


def _avatar_board(**bob) -> Scenario:
    return (
        Scenario()
        .player(
            "alice",
            hand=["Enter the Avatar State"],
            battlefield=["Plains", "Grizzly Bears"],
        )
        .player("bob", **bob)
    )


def _cast_avatar(scenario: Scenario):
    bears = scenario.creature("Grizzly Bears", "alice")
    (plains,) = scenario.untapped_sources("Plains", username="alice")
    scenario.cast_and_resolve("Enter the Avatar State", plains, targets=[bears])
    return bears


def test_enter_the_avatar_state_adds_the_subtype_and_all_four_keywords():
    scenario = _avatar_board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = _cast_avatar(scenario)

    board = computed(scenario).of(bears)
    assert "Avatar" in board.subtypes
    assert "Bear" in board.subtypes, "CR 205.1b: the old subtype is retained"
    assert board.is_creature
    for keyword in (Keyword.FLYING, Keyword.FIRST_STRIKE, Keyword.LIFELINK):
        assert has_keyword(bears, keyword, scenario.game), keyword
    assert board.has_ability("Hexproof")
    assert board.power_toughness == (2, 2), "no P/T change in this instruction"
    assert notices(scenario) == []


def test_the_type_and_the_grants_are_layer_4_and_layer_6_with_one_timestamp():
    scenario = _avatar_board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = _cast_avatar(scenario)

    effects = scenario.game.continuous_effects.effects
    assert {getattr(effect.selector, "card_id", None) for effect in effects} == {bears.id}
    layers = sorted(effect.layer.value for effect in effects)
    assert layers.count(Layer.TYPE.value) == 1
    assert layers.count(Layer.ABILITY.value) == 4
    assert len({effect.timestamp for effect in effects}) == 1


def test_hexproof_granted_stops_an_opponents_spell_targeting_it():
    """CR 702.11b on a real opponent's Lightning Bolt."""
    scenario = _avatar_board(hand=["Lightning Bolt"], battlefield=["Mountain"]).build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = _cast_avatar(scenario)

    with pytest.raises(ValueError):
        scenario.cast("Lightning Bolt", "bob", targets=[bears])


def test_everything_ends_together_in_the_cleanup_step():
    scenario = _avatar_board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = _cast_avatar(scenario)

    scenario.start_at(Step.END_STEP)
    assert "Avatar" in computed(scenario).of(bears).subtypes
    scenario.advance()  # cleanup

    board = computed(scenario).of(bears)
    assert "Avatar" not in board.subtypes
    assert "Bear" in board.subtypes
    assert not has_keyword(bears, Keyword.FLYING, scenario.game)
    assert not board.has_ability("Hexproof")


def test_the_target_must_be_a_creature_you_control():
    scenario = _avatar_board(battlefield=["Grizzly Bears"]).build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    theirs = scenario.creature("Grizzly Bears", "bob")

    with pytest.raises(ValueError):
        scenario.cast("Enter the Avatar State", "alice", targets=[theirs])


def test_a_target_gone_before_resolution_gets_nothing_and_logs_nothing():
    """CR 608.2b: the only target is illegal, so the spell does nothing; the
    creature that comes back is a new object (CR 400.7) the effect never
    names."""
    scenario = _avatar_board().build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    (plains,) = scenario.untapped_sources("Plains", username="alice")
    scenario.cast_onto_stack("Enter the Avatar State", plains, targets=[bears])
    scenario.game.return_to_hand(bears)
    scenario.pass_until_resolved()

    assert scenario.game.continuous_effects.effects == []
    assert notices(scenario) == []


# -- second printing: Archangel Elspeth -----------------------------------


def _elspeth() -> Scenario:
    scenario = (
        Scenario()
        .player("alice", battlefield=["Archangel Elspeth", "Grizzly Bears"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


def _minus_two(scenario: Scenario):
    elspeth = scenario.find("Archangel Elspeth", Zone.BATTLEFIELD, "alice")
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.activate(elspeth, index=1, targets=[bears])
    scenario.pass_until_resolved()
    return bears


def test_elspeth_minus_two_counters_then_angel_in_addition_with_flying():
    """ "Put two +1/+1 counters on target creature. It becomes an Angel in
    addition to its other types and gains flying." - the counters, then both
    layers on the same object ("It", CR 608.2c)."""
    scenario = _elspeth()
    bears = _minus_two(scenario)

    board = computed(scenario).of(bears)
    assert "Angel" in board.subtypes
    assert "Bear" in board.subtypes
    assert has_keyword(bears, Keyword.FLYING, scenario.game)
    assert board.power_toughness == (4, 4), "a 2/2 with two +1/+1 counters"
    assert notices(scenario) == []


def test_with_no_stated_duration_it_outlasts_the_turn():
    """CR 611.2a: "If no duration is stated, it lasts until the end of the
    game." - unlike Enter the Avatar State, nothing ends in the cleanup step."""
    scenario = _elspeth()
    bears = _minus_two(scenario)

    scenario.start_at(Step.END_STEP)
    scenario.advance()  # cleanup

    board = computed(scenario).of(bears)
    assert "Angel" in board.subtypes
    assert has_keyword(bears, Keyword.FLYING, scenario.game)


def test_a_new_object_is_not_the_angel():
    """CR 400.7: returned to hand and replayed, it is a new object the effect
    never named."""
    scenario = _elspeth()
    bears = _minus_two(scenario)
    scenario.game.return_to_hand(bears)
    again = scenario.put_onto_battlefield("Grizzly Bears", "alice")

    board = computed(scenario).of(again)
    assert "Angel" not in board.subtypes
    assert not has_keyword(again, Keyword.FLYING, scenario.game)
