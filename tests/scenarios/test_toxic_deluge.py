"""Scenario: Toxic Deluge - "As an additional cost to cast this spell, pay X
life. All creatures get -X/-X until end of turn."

X is announced once, at cost determination (CR 601.2b/107.3a), and feeds two
independent things that must stay in lockstep: the life paid as an additional
cost (CR 118.8a) and the magnitude of the mass debuff (CR 611.2, CR 611.2c).
Getting the order backwards - choosing X after seeing what the board looks
like - would be CR 107.3a's own mistake, so this file drives X through
`Casting.determine_cost` before the board is ever touched, the same way a
real cast announces it before anything resolves.

The mass debuff itself reuses `machines/layers.py`'s `_mass_pump_until_eot_
builder`/`_run_mass_pump` (CR 611.2's one-shot, CR 611.2c's fixed-at-
resolution group) with a negative magnitude and no controller restriction -
the "all creatures" shape this wave added alongside the existing "creatures
you control"/"creatures your opponents control" ones.

Every CR number here was looked up with `knowledge_search(q="...",
type="rules")` in the session that wrote this file:

- **CR 118.8a** - an additional cost is paid on the way to the stack.
- **CR 119.4** - "If a cost or effect allows a player to pay an amount of
  life greater than 0, the player may do so only if their life total is
  greater than or equal to the amount of the payment."
- **CR 611.2a** - "A continuous effect generated by the resolution of a spell
  or ability lasts as long as stated by the spell or ability creating it."
- **CR 611.2c** - the set of objects a resolution-generated continuous
  effect affects is fixed when it begins.
- **CR 704.5f** - a creature with toughness 0 or less is put into its
  owner's graveyard (a state-based action, not part of the effect itself).
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.machines.casting import Casting
from magic_cards_model.machines.cost import TotalCost, pay_life_cost
from magic_cards_model.machines.modes import substitute_x
from magic_cards_model.models import Zone
from tests.scenarios.harness import PlayedScenario, Scenario


def _to_main(scenario) -> None:
    scenario.start_at(Step.PRECOMBAT_MAIN)


def _cast_paying_x_life(
    scenario: PlayedScenario, x_value: int, *sources, username: str = "alice"
) -> Casting:
    """Announce Toxic Deluge for a chosen X, paying that much life as the
    additional cost (CR 118.8a) - the same manual wiring `test_costs.py`
    already uses for Fumarole's fixed "pay 3 life".
    """
    casting = scenario.cast("Toxic Deluge", username=username)
    casting.game = scenario.game
    casting.add_additional_cost(TotalCost.of(None, pay_life_cost(x_value)))
    casting.determine_cost(x_value=x_value)
    payment = casting.begin_paying()
    scenario.pay_with(payment, *sources)
    scenario.put_on_stack(casting)
    return casting


def test_toxic_deluge_kills_small_creatures_and_shrinks_big_ones():
    """X=2: a 2/2 dies to the state-based action (0 toughness), and a bigger
    creature survives merely smaller.
    """
    scenario = (
        Scenario()
        .player(
            "alice",
            life=20,
            hand=["Toxic Deluge"],
            battlefield=["Swamp", "Swamp", "Swamp"],
        )
        .player("bob", battlefield=["Elvish Mystic", "Wood Elves"])
        .build()
    )
    _to_main(scenario)
    mystic = scenario.creature("Elvish Mystic", "bob")
    elves = scenario.creature("Wood Elves", "bob")
    assert elves.power == 1 and elves.toughness == 1
    # Wood Elves is a 1/1; give it more toughness so the "shrinks but lives"
    # half of this test is meaningful - use its counters directly (staging,
    # not mocking: the same primitive any +1/+1-counter effect uses).
    scenario.game.add_counters(elves, "+1/+1", 3)
    assert elves.toughness == 4

    sources = scenario.untapped_sources("Swamp", "Swamp", "Swamp")
    _cast_paying_x_life(scenario, 2, *sources)
    scenario.resolve_top()
    scenario.state_based_actions()

    assert mystic.zone is Zone.GRAVEYARD, "a 1/1 minus 2/2 has 0 toughness"
    assert elves.zone is Zone.BATTLEFIELD
    live = scenario.game.characteristics_of(elves)
    assert live.power == 2 and live.toughness == 2, "4/4 minus 2/2 survives, smaller"


def test_toxic_deluge_pays_life_as_an_additional_cost():
    """CR 118.3b: paying life subtracts it from the life total, at the
    moment the cost is paid - before the spell even resolves.
    """
    scenario = (
        Scenario()
        .player("alice", life=20, hand=["Toxic Deluge"], battlefield=["Swamp", "Swamp", "Swamp"])
        .build()
    )
    _to_main(scenario)

    sources = scenario.untapped_sources("Swamp", "Swamp", "Swamp")
    _cast_paying_x_life(scenario, 4, *sources)

    assert scenario.player("alice").life == 16


def test_toxic_deluge_x_zero_does_nothing():
    """X=0 pays no life and the debuff is -0/-0 - nothing dies, nothing
    shrinks. `_run_mass_pump`'s own caller refuses to build an effect for a
    non-positive X rather than construct a no-op "-0/-0" continuous effect.
    """
    scenario = (
        Scenario()
        .player("alice", life=20, hand=["Toxic Deluge"], battlefield=["Swamp", "Swamp", "Swamp"])
        .player("bob", battlefield=["Elvish Mystic"])
        .build()
    )
    _to_main(scenario)
    mystic = scenario.creature("Elvish Mystic", "bob")

    sources = scenario.untapped_sources("Swamp", "Swamp", "Swamp")
    _cast_paying_x_life(scenario, 0, *sources)
    scenario.resolve_top()
    scenario.state_based_actions()

    assert scenario.player("alice").life == 20
    assert mystic.zone is Zone.BATTLEFIELD


def test_toxic_deluge_life_cannot_be_paid_below_the_amount_available():
    """CR 119.4: life may only be paid if the life total is at least the
    amount - alice at 3 life cannot pay X=5.
    """
    scenario = (
        Scenario().player("alice", life=3, hand=["Toxic Deluge"], battlefield=["Swamp"] * 6).build()
    )
    _to_main(scenario)

    casting = scenario.cast("Toxic Deluge")
    casting.game = scenario.game
    casting.add_additional_cost(TotalCost.of(None, pay_life_cost(5)))
    casting.determine_cost(x_value=5)
    payment = casting.begin_paying()
    sources = scenario.untapped_sources(*(["Swamp"] * 6))

    with pytest.raises(ValueError, match="cannot pay 5 life"):
        scenario.pay_with(payment, *sources)


def test_toxic_deluges_debuff_hits_every_creature_regardless_of_controller():
    """ "All creatures" - unlike a "creatures you control" anthem, Toxic
    Deluge is a symmetrical sweeper: alice's own creature is not spared.
    """
    scenario = (
        Scenario()
        .player(
            "alice",
            life=20,
            hand=["Toxic Deluge"],
            battlefield=["Swamp", "Swamp", "Swamp", "Elvish Mystic"],
        )
        .player("bob", battlefield=["Elvish Mystic"])
        .build()
    )
    _to_main(scenario)
    alices_mystic = scenario.creature("Elvish Mystic", "alice")
    bobs_mystic = scenario.creature("Elvish Mystic", "bob")

    sources = scenario.untapped_sources("Swamp", "Swamp", "Swamp")
    _cast_paying_x_life(scenario, 1, *sources)
    scenario.resolve_top()
    scenario.state_based_actions()

    assert alices_mystic.zone is Zone.GRAVEYARD
    assert bobs_mystic.zone is Zone.GRAVEYARD


def test_the_additional_cost_phrase_reads_x_life_with_substitute_x():
    """`additional_cost_phrases` reads the printed sentence as "pay X life" -
    `modes.substitute_x` turns it into the existing "pay N life" shape
    `machines/cost.py`'s own `_PHRASE_PAY_LIFE` regex already reads, with no
    new cost-parsing regex needed for the variable amount.
    """
    from magic_cards_model.machines.cost import additional_cost_phrases
    from tests.cards import card

    phrases = additional_cost_phrases(card("Toxic Deluge"))
    assert phrases == ["pay X life"]
    assert substitute_x(phrases[0], 3) == "pay 3 life"
