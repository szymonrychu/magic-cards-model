"""Ardoz, Cobbler of War's own "Whenever Ardoz or another creature you
control enters, that creature gets +2/+0 until end of turn." - the trigger
condition already fires for either half of "`<self>` or another creature you
control enters" (an earlier wave); the resolved effect body did not: "that
creature" is CR 400.7's plain anaphor back to the *triggering event's own
subject* - whichever creature actually entered - not the ability's own
source the way a bare, subject-less "This creature gets ..." (Basking
Rootwalla) correctly falls back to.

`create_continuous_effect_of_ability`'s own "the ability names no target ->
the object is its own source" rule is right for Basking Rootwalla and wrong
here: Ardoz's own trigger fires just as often on a *different* creature
entering as on himself, and defaulting to `[source]` would pump Ardoz every
time regardless of which creature actually triggered it.

`_parse_event_subject_pump_clause` (`machines/effects.py`) reads the shape
before that default is ever reached, rewriting "that creature"/"it" to
"target creature" - a textual stand-in only, exactly as `_RIDER_LAYER_
SUBJECT_RE`'s own "It gets +N/+N ..." rider already relies on - so `machines/
layers.py` needs no changes at all; the real object list comes from
`AbilityOnStack.event.subject_id` instead of from `Game.resolve_card_
targets`. Ambuscade Shaman is the off-pool generality proof - a different
pump amount (+2/+2, not +2/+0) and "this creature" rather than a literal
name self-reference.

Verified this session with `mise run rules:find` (on-disk CR effective
2026-09-25):

- **CR 400.7** - an object that changes zones becomes a new object; "that
  creature" is Oracle's own anaphor back to the one the event just happened
  to, read here off `GameEvent.subject_id` - the same field `event_subject_
  power` already reads for a dying creature's power.
- **CR 611.2/611.2a** - the pump itself, a continuous effect generated by a
  resolving ability, lasting until end of turn.
- **CR 611.2c** - "the set of objects [a characteristic-modifying continuous
  effect] affects is determined when that continuous effect begins" - fixed
  once, to whichever single creature entered, never re-derived later.
"""

from magic_cards_model.machines import Step
from tests.scenarios.harness import Scenario


def computed(scenario: Scenario):
    """The board with static abilities and stored durational effects applied."""
    return scenario.game.continuous_effects.board(scenario.game.battlefield)


def test_ardoz_pumps_himself_when_he_enters():
    scenario = (
        Scenario()
        .player("alice", hand=["Ardoz, Cobbler of War"], battlefield=["Mountain", "Mountain"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)

    ardoz = scenario.cast_and_resolve(
        "Ardoz, Cobbler of War", *scenario.untapped_sources("Mountain", "Mountain")
    )
    scenario.resolve_top()  # the enters trigger

    assert computed(scenario).of(ardoz).power_toughness == (3, 1), "a 1/1 plus a temporary +2/+0"


def test_ardoz_pumps_a_different_creature_entering_not_himself():
    """The reported gap: Ardoz already on the battlefield, and a *different*
    creature entering is the one that gets +2/+0 - not Ardoz, which the old
    "no target names -> the source" default would have wrongly pumped
    instead."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Grizzly Bears"],
            battlefield=["Ardoz, Cobbler of War", "Forest", "Forest"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    ardoz = scenario.creature("Ardoz, Cobbler of War", "alice")

    bears = scenario.cast_and_resolve(
        "Grizzly Bears", *scenario.untapped_sources("Forest", "Forest")
    )
    scenario.resolve_top()  # the enters trigger

    assert computed(scenario).of(bears).power_toughness == (4, 2), "the bears, plus +2/+0"
    assert computed(scenario).of(ardoz).power_toughness == (1, 1), "Ardoz himself, untouched"


def test_ambuscade_shaman_pumps_a_different_entering_creature_off_pool():
    """Off-pool generality proof: Ambuscade Shaman's identical shape, printed
    with "this creature" rather than a literal name, and a different pump
    amount (+2/+2, not +2/+0)."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Grizzly Bears"],
            battlefield=["Ambuscade Shaman", "Forest", "Forest"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    shaman = scenario.creature("Ambuscade Shaman", "alice")

    bears = scenario.cast_and_resolve(
        "Grizzly Bears", *scenario.untapped_sources("Forest", "Forest")
    )
    scenario.resolve_top()  # the enters trigger

    assert computed(scenario).of(bears).power_toughness == (4, 4), "the bears, plus +2/+2"
    assert computed(scenario).of(shaman).power_toughness == (2, 2), "the Shaman itself, untouched"
