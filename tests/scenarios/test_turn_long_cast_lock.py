""" "Your opponents can't cast spells [or activate planeswalkers' loyalty
abilities] this turn." - a resolving spell's turn-long lock.

CR 601.3: "A player can begin to cast a spell only if a rule or effect allows
that player to cast it and no rule or effect prohibits that player from
casting it." CR 602.5: "A player can't begin to activate an ability that's
prohibited from being activated." CR 101.2 gives either "can't" precedence
over any permission.

CR 611.2c: "A continuous effect generated by the resolution of a spell or
ability that doesn't modify the characteristics or change the controller of
any objects modifies the rules of the game, so it can affect objects that
weren't affected when that continuous effect began." - so the lock is
recorded on the game (`Game.casting_rule_effects`) and read at each later
cast or activation, never tied to a permanent. "This turn" ends in
the cleanup step (CR 514.2).

CR 606.3 is the loyalty ability being locked; CR 605.1a is why a mana
ability or any non-loyalty activation is not.

Revel in Silence (the back face of Flamescroll Celebrant, cast under CR
712.11b) is the listed card and also exiles itself (CR 201.5: a card naming
itself means that object). Silence - Modern/Pioneer-legal, in no api deck -
is the proof printing: the same sentence without the loyalty half, and no
self-exile.

Every CR number here was looked up with `mise run rules:find` in the session
that wrote it.
"""

import pytest

from magic_cards_model.machines import Step
from magic_cards_model.machines.keywords import cycling_activation
from magic_cards_model.models import CardState, Zone
from magic_cards_model.models.action import ActionKind
from magic_cards_model.support import classify_clauses
from tests.cards import card
from tests.scenarios.harness import Scenario, mana_from

CELEBRANT = "Flamescroll Celebrant"
CELEBRANT_CARD = "Flamescroll Celebrant // Revel in Silence"
REVEL = "Revel in Silence"


def cast_revel(scenario, username: str = "alice") -> CardState:
    """Cast the instant back face (CR 712.11b) and let it resolve."""
    if scenario.priority_holder != username:
        scenario.pass_priority(scenario.priority_holder)
    casting = scenario.cast(CELEBRANT, username)
    casting.cast_as_split_half(REVEL)
    payment = casting.begin_paying()
    scenario.pay_with(payment, *scenario.untapped_sources("Plains", "Plains", username=username))
    spell = scenario.put_on_stack(casting)
    scenario.pass_until_resolved()
    return spell


def test_revel_stops_an_opponent_casting_spells() -> None:
    scenario = (
        Scenario()
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .player("bob", hand=["Lightning Bolt"], battlefield=["Mountain"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)

    cast_revel(scenario)

    with pytest.raises(ValueError, match="can't cast spells"):
        scenario.cast("Lightning Bolt", username="bob")


def test_revel_exiles_itself() -> None:
    """ "Exile Revel in Silence." - the resolving card goes to exile, not the
    graveyard, and is the front face again there (CR 712.8a)."""
    scenario = (
        Scenario()
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)

    spell = cast_revel(scenario)

    assert spell.zone is Zone.EXILE
    assert spell.name == CELEBRANT


def test_revel_stops_an_opponents_loyalty_activation() -> None:
    """Cast at instant speed on Bob's own turn: his planeswalker's loyalty
    abilities are locked for the rest of it (CR 602.5, CR 606.3)."""
    scenario = (
        Scenario()
        .player("bob", battlefield=["Garruk, Veiled Butcher"])
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    garruk = scenario.find("Garruk, Veiled Butcher", Zone.BATTLEFIELD, "bob")
    assert scenario.why_cannot_activate(garruk, 0, "bob") is None

    cast_revel(scenario)

    reason = scenario.why_cannot_activate(garruk, 0, "bob")
    assert reason is not None and "loyalty" in reason
    with pytest.raises(ValueError, match="loyalty"):
        scenario.activate(garruk, index=0, targets=[], username="bob")


def test_revel_leaves_other_activations_alone() -> None:
    """Only loyalty abilities are named: a mana ability (CR 605.1a) and a
    cycling ability (CR 702.29a) are still activated freely."""
    scenario = (
        Scenario()
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .player("bob", hand=["Censor"], library=["Island"], battlefield=["Island", "Mountain"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    cast_revel(scenario)
    scenario.pass_priority("alice")

    censor = scenario.find("Censor", Zone.HAND, "bob")
    activation = cycling_activation(scenario.game, censor, "bob")
    payment = activation.begin_paying()
    (island,) = scenario.untapped_sources("Island", username="bob")
    payment.tap_for_mana(island, mana_from(island))
    payment.pay()
    activation.activate()
    assert censor.zone is Zone.GRAVEYARD


def test_revel_does_not_restrict_its_caster() -> None:
    """ "Your opponents" - Alice herself may still cast spells."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=[CELEBRANT_CARD, "Lightning Bolt"],
            battlefield=["Plains", "Plains", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    cast_revel(scenario)

    scenario.cast_and_resolve(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    assert scenario.player("bob").life == 17


def test_a_spell_already_on_the_stack_still_resolves() -> None:
    """CR 601.3 is asked as a spell is cast: Bob's Bolt, cast before Revel
    resolved, is not unmade by it."""
    scenario = (
        Scenario()
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .player("bob", hand=["Lightning Bolt"], battlefield=["Mountain"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    scenario.pass_priority("alice")
    scenario.cast_onto_stack(
        "Lightning Bolt",
        *scenario.untapped_sources("Mountain", username="bob"),
        username="bob",
        targets=["alice"],
    )

    cast_revel(scenario)  # resolves on top of the Bolt
    scenario.pass_until_resolved()

    assert scenario.player("alice").life == 17


def test_the_lock_ends_with_the_turn() -> None:
    """CR 514.2: "this turn" effects end in the cleanup step."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=[CELEBRANT_CARD],
            battlefield=["Plains", "Plains"],
            library=["Plains"] * 3,
        )
        .player("bob", hand=["Lightning Bolt"], battlefield=["Mountain"], library=["Mountain"] * 3)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    cast_revel(scenario)

    while scenario.step is not Step.END_STEP:
        scenario.advance()
    with pytest.raises(ValueError, match="can't cast spells"):
        scenario.cast("Lightning Bolt", username="bob")

    while scenario.turn.active_player != "bob" or scenario.step is not Step.PRECOMBAT_MAIN:
        scenario.advance()
    assert scenario.game.casting_rule_effects == []
    assert scenario.cast("Lightning Bolt", username="bob") is not None


def test_legal_actions_drop_the_locked_casts_and_loyalty_activations() -> None:
    """`legal_actions` offers Bob neither a cast nor a loyalty activation
    while the lock holds, but still his mana ability."""
    scenario = (
        Scenario()
        .player("bob", hand=["Lightning Bolt"], battlefield=["Garruk, Veiled Butcher", "Mountain"])
        .player("alice", hand=[CELEBRANT_CARD], battlefield=["Plains", "Plains"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    garruk = scenario.find("Garruk, Veiled Butcher", Zone.BATTLEFIELD, "bob")
    before = {action.kind for action in scenario.game.legal_actions("bob")}
    assert ActionKind.CAST in before and ActionKind.ACTIVATE in before

    cast_revel(scenario)
    if scenario.priority_holder != "bob":
        scenario.pass_priority(scenario.priority_holder)
    actions = scenario.game.legal_actions("bob")

    assert not [action for action in actions if action.kind is ActionKind.CAST]
    assert not [
        action
        for action in actions
        if action.kind is ActionKind.ACTIVATE and action.card_id == garruk.id
    ]
    assert [action for action in actions if action.kind is ActionKind.ACTIVATE_MANA]


def test_silence_stops_an_opponent_casting_but_not_its_caster() -> None:
    """Proof printing: "Your opponents can't cast spells this turn." alone."""
    scenario = (
        Scenario()
        .player("alice", hand=["Silence", "Lightning Bolt"], battlefield=["Plains", "Mountain"])
        .player("bob", hand=["Lightning Bolt"], battlefield=["Mountain"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)

    silence = scenario.cast_and_resolve("Silence", *scenario.untapped_sources("Plains"))

    assert silence.zone is Zone.GRAVEYARD
    with pytest.raises(ValueError, match="can't cast spells"):
        scenario.cast("Lightning Bolt", username="bob")
    scenario.cast_and_resolve(
        "Lightning Bolt", *scenario.untapped_sources("Mountain"), targets=["bob"]
    )
    assert scenario.player("bob").life == 17


def test_silence_does_not_lock_loyalty_abilities() -> None:
    """Silence names spells only - Bob's planeswalker still activates."""
    scenario = (
        Scenario()
        .player("bob", battlefield=["Garruk, Veiled Butcher"])
        .player("alice", hand=["Silence"], battlefield=["Plains"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    garruk = scenario.find("Garruk, Veiled Butcher", Zone.BATTLEFIELD, "bob")
    scenario.pass_priority("bob")
    scenario.cast_and_resolve(
        "Silence", *scenario.untapped_sources("Plains", username="alice"), username="alice"
    )

    assert scenario.why_cannot_activate(garruk, 0, "bob") is None


def test_the_sweep_reads_both_lock_spells() -> None:
    """Every clause of Flamescroll Celebrant // Revel in Silence and of
    Silence is handled - the back face's lines are its resolution, judged
    as a "[spell]" clause, never an unaudited static of the creature."""
    for name in (CELEBRANT_CARD, "Silence"):
        outcomes = classify_clauses(card(name))
        assert outcomes, name
        assert {outcome.category for outcome in outcomes} == {"handled"}, (name, outcomes)
