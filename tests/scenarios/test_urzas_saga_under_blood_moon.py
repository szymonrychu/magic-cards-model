def test_before_any_chapter_it_is_a_mountain_and_nothing_else():
    """The other end of the story: Blood Moon lands before chapter I ever
    resolved, so there is no CR 611.2 effect to survive. Layer 4 strips the
    text and layer 6 has nothing to put back - one bare red mana ability.

    Built by putting the Saga onto the battlefield directly, which is the one
    place in this file that is *wanted*: it must not run chapter I.
    """
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Blood Moon"],
            battlefield=["Urza's Saga", "Mountain", "Mountain", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    saga = scenario.find("Urza's Saga", Zone.BATTLEFIELD)
    assert saga.granted_ability_texts == ()

    _cast_blood_moon(scenario)

    assert _abilities(scenario, saga) == {"{T}: Add {R}."}
    assert set(scenario.game.characteristics_of(saga).subtypes) == {"Mountain"}
    assert not saga.is_saga
    assert saga.chapter_numbers == ()


def test_before_any_chapter_it_is_still_not_sacrificed():
    """Same permanent, same rule: no chapter abilities means CR 704.5s never
    applies, however many lore counters end up on it."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Blood Moon"],
            battlefield=["Urza's Saga", "Mountain", "Mountain", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    saga = scenario.find("Urza's Saga", Zone.BATTLEFIELD)
    _cast_blood_moon(scenario)

    saga.add_counters("lore", 3)
    scenario.game.check_state_based_actions()

    assert saga.zone is Zone.BATTLEFIELD


def test_before_any_chapter_no_lore_counter_arrives_either():
    """CR 505.4's turn-based action passes it by, so the story never starts."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Blood Moon"],
            battlefield=["Urza's Saga", "Mountain", "Mountain", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    saga = scenario.find("Urza's Saga", Zone.BATTLEFIELD)
    _cast_blood_moon(scenario)
    before = saga.lore_counters

    scenario.game.saga_lore_step()

    assert saga.lore_counters == before


# --------------------------------------------------------------------------
# The control: without Blood Moon, everything above must be false
# --------------------------------------------------------------------------


def test_without_blood_moon_the_saga_is_sacrificed_after_chapter_three():
    """The control the rest of the file is measured against. Left to itself the
    Saga does have three chapter abilities, does reach final chapter 3
    (CR 714.2d), and CR 704.5s does put it into its owner's graveyard - so
    every "it survives" above is a statement about Blood Moon and not about a
    state-based action the engine simply never runs."""
    scenario, saga = _saga_on_the_battlefield(chapters=2)
    assert saga.is_saga
    assert saga.chapter_numbers == (1, 2, 3)
    assert saga.final_chapter_number == 3
    assert saga.lore_counters == 2
    assert saga.zone is Zone.BATTLEFIELD

    # The third lore counter takes it to its final chapter number, and the
    # state-based action `resolve_top` already runs alongside chapter III fires
    # the moment that chapter ability has left the stack (CR 704.5s's own "and
    # it isn't the source of a chapter ability that has triggered but not yet
    # left the stack").
    scenario.game.saga_lore_step()
    _settle(scenario)

    assert saga.zone is Zone.GRAVEYARD


def test_without_blood_moon_it_is_a_saga_and_collects_lore_counters():
    """The other control: the lore counter really does arrive each precombat
    main phase while the chapter abilities are there to earn it."""
    scenario, saga = _saga_on_the_battlefield(chapters=1)

    assert saga.is_saga
    assert saga.lore_counters == 1

    scenario.game.saga_lore_step()

    assert saga.lore_counters == 2
