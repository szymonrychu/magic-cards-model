"""Scenario: Urza's Saga meeting Blood Moon, and what survives the meeting.

`test_urzas_saga.py` covers the card playing out normally. This file covers the
one interaction that makes it famous, and it is famous because the answer runs
against every instinct: a Blood Mooned Urza's Saga is **never sacrificed**, and
it **keeps the abilities its chapters already gave it**.

Card text, verified with `resolve_cards` in the session that wrote this file:

- **Urza's Saga**, "Enchantment Land - Urza's Saga": "(As this Saga enters and
  after your draw step, add a lore counter. Sacrifice after III.) I - This Saga
  gains "{T}: Add {C}." II - This Saga gains "{2}, {T}: Create a 0/0 colorless
  Construct artifact creature token with 'This token gets +1/+1 for each
  artifact you control.'" III - Search your library for an artifact card with
  mana cost {0} or {1}, put it onto the battlefield, then shuffle."
- **Blood Moon**, Enchantment: "Nonbasic lands are Mountains."

Every CR number below was looked up with `knowledge_search(q="...",
type="rules")` in the session that wrote this file:

- **CR 613.1d** - layer 4 is type-changing. Blood Moon is here.
- **CR 613.1f** - layer 6 is "Ability-adding effects, keyword counters,
  ability-removing effects". The chapter grants are here, and layer 6 is
  applied **after** layer 4. That single ordering fact is the whole reason the
  grants survive.
- **CR 305.7** - "If an effect sets a land's subtype to one or more of the
  basic land types, the land no longer has its old land type. It loses all
  abilities generated from its rules text, its old land types, and any..."
  **`knowledge_search` truncates this rule at "and any" on every phrasing
  tried in this session.** Nothing below depends on the missing tail: the two
  clauses that do come back - the old land type goes, and the abilities
  generated from the *rules text* go - are all that is used, and the tail is
  neither quoted nor guessed at.
- **CR 611.2** - "a continuous effect [may be] generated by the resolution of a
  spell or ability". A chapter ability that already resolved created its own
  continuous effect; that effect is not "generated from Urza's Saga's rules
  text" any more, it is generated by the resolution that happened, so CR 305.7
  has no grip on it.
- **CR 611.1** - a continuous effect lasts "for a fixed or indefinite period";
  neither chapter states a duration, so both grants are indefinite.
- **CR 305.6** - a land with a basic land type has the intrinsic "{T}: Add
  [mana symbol]", which is where the Mountain's {R} comes from.
- **CR 107.15** - chapter symbols "are keyword abilities that represent
  triggered abilities".
- **CR 714.2d** - "A Saga's final chapter number is the greatest value among
  chapter abilities it **has**. If a Saga somehow has no chapter abilities, its
  final chapter number is 0."
- **CR 714.4** and **CR 704.5s** - the state-based action applies to "a Saga
  permanent **with one or more chapter abilities**" whose lore counters are at
  least its final chapter number. That qualifier is what makes a Saga with no
  chapter abilities immortal rather than instantly dead at final chapter 0 -
  read the two rules in that order and the CR 714.2d trap disarms itself.
- **CR 505.4** and **CR 714.3c** - the precombat main phase puts a lore counter
  on each Saga its controller controls "**with one or more chapter
  abilities**". Same qualifier, same consequence.
- **CR 303.5** - a Saga is an enchantment with the Saga subtype, which under
  Blood Moon it no longer has.
- **CR 613.5** - the layer system is "continually and automatically" applied,
  so "is this a Saga" and "which chapter abilities does it have" are questions
  about the computed board, not about the printing.

## The chain, stated once

1. Blood Moon is a layer 4 effect (CR 613.1d) that *sets* Urza's Saga's subtype
   to Mountain. CR 305.7 therefore takes away its old subtypes - including
   "Saga" - and every ability its rules text generated, which is all three
   chapter abilities (CR 107.15).
2. It is now not a Saga (CR 303.5) and has no chapter abilities. CR 505.4 /
   CR 714.3c stop giving it lore counters, and CR 714.4 / CR 704.5s do not
   apply to it, so it is never put into the graveyard. Its final chapter number
   would be 0 by CR 714.2d - which would be lethal if the "with one or more
   chapter abilities" qualifier were not there, and is the trap this file
   exists to pin.
3. The abilities chapters I and II already granted are separate continuous
   effects from their own resolutions (CR 611.2), applied in layer 6
   (CR 613.1f) - after layer 4. Layer 4 stripping the printed text cannot reach
   them, so they stay.
4. Net: a land that taps for {C} (chapter I's grant) or for {R} (the Mountain's
   intrinsic ability, CR 305.6), still makes Constructs (chapter II's grant),
   and cannot die to its own Saga rules.
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Color, Zone
from tests.scenarios.harness import Scenario


def _saga_on_the_battlefield(*, chapters, hand=(), battlefield=()):
    """Urza's Saga played from hand and advanced `chapters` chapters.

    Played rather than placed straight onto the battlefield for the reason
    `test_urzas_saga.py`'s own helper documents: a card built directly into
    `battlefield=[...]` never runs `Game.enter_the_battlefield`, so CR 714.3a's
    intrinsic entering lore counter never fires chapter I.
    """
    scenario = (
        Scenario()
        .player("alice", hand=["Urza's Saga", *hand], battlefield=list(battlefield))
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    saga = scenario.play_land("Urza's Saga")
    _settle(scenario)
    for _ in range(chapters - 1):
        scenario.game.saga_lore_step()  # CR 505.4 / 714.3c
        _settle(scenario)
    return scenario, saga


def _settle(scenario):
    scenario.game.put_triggers_on_stack()
    while scenario.game.stack:
        scenario.resolve_top()


def _cast_blood_moon(scenario):
    scenario.start_at(Step.PRECOMBAT_MAIN)
    sources = scenario.untapped_sources("Mountain", "Mountain", "Mountain")
    return scenario.cast_and_resolve("Blood Moon", *sources)


def _abilities(scenario, permanent):
    return set(scenario.game.characteristics_of(permanent).abilities)


def _index_of(scenario, permanent, raw):
    """Where an ability sits in `Game.activated_abilities`, which is the index
    `begin_activating` keys on. Looked up by text rather than hardcoded,
    because Blood Moon changes what is at position 0: the Mountain's intrinsic
    ability comes off the computed line list and the chapter grants are
    appended after it."""
    abilities = scenario.game.activated_abilities(permanent)
    return next(index for index, ability in enumerate(abilities) if ability.raw == raw)


# --------------------------------------------------------------------------
# Mid-story: chapters I and II have resolved, then Blood Moon lands
# --------------------------------------------------------------------------


def _mid_story(extra_battlefield=()):
    """A Saga on chapter II - both grants live - with Blood Moon then cast."""
    scenario, saga = _saga_on_the_battlefield(
        chapters=2,
        hand=["Blood Moon"],
        battlefield=["Mountain", "Mountain", "Mountain", *extra_battlefield],
    )
    assert saga.lore_counters == 2
    assert saga.granted_ability_texts == (
        "{T}: Add {C}.",
        "{2}, {T}: Create a 0/0 colorless Construct artifact creature token with "
        "'This token gets +1/+1 for each artifact you control.'",
    )
    _cast_blood_moon(scenario)
    return scenario, saga


def test_mid_story_it_stops_being_a_saga_at_all():
    """CR 305.7 takes the old land types, "Urza's" and "Saga" among them, and
    CR 303.5's "enchantment with the Saga subtype" then has nothing to hold."""
    scenario, saga = _mid_story()

    assert set(scenario.game.characteristics_of(saga).subtypes) == {"Mountain"}
    assert not saga.is_saga


def test_mid_story_the_printed_chapter_abilities_are_gone():
    """CR 107.15 makes each chapter symbol a triggered ability, and CR 305.7
    removes every ability generated from the land's rules text. CR 714.2d then
    reads "the greatest value among chapter abilities it **has**" off an empty
    list."""
    scenario, saga = _mid_story()

    assert saga.chapter_numbers == ()
    assert saga.final_chapter_number is None
    printed = scenario.game.characteristics_of(saga).abilities
    assert not any(line.startswith(("I ", "II ", "III ")) for line in printed)


def test_mid_story_it_is_never_sacrificed():
    """The headline. CR 714.4 and CR 704.5s both apply only to "a Saga
    permanent **with one or more chapter abilities**", and this permanent has
    none - so the state-based action does not look at it, whatever its lore
    counters say. Checked after an explicit state-based-action pass so the
    absence is a real answer and not merely an unasked question.
    """
    scenario, saga = _mid_story()

    scenario.game.check_state_based_actions()

    assert saga.zone is Zone.BATTLEFIELD


def test_mid_story_it_stops_getting_lore_counters():
    """CR 505.4 / CR 714.3c put a lore counter only on a Saga "with one or more
    chapter abilities". Two main phases go by and the count does not move."""
    scenario, saga = _mid_story()
    assert saga.lore_counters == 2

    scenario.game.saga_lore_step()
    scenario.game.saga_lore_step()

    assert saga.lore_counters == 2


def test_mid_story_lore_counters_frozen_below_three_still_never_kill_it():
    """The two halves together, which is where a naive implementation goes
    wrong twice and gets the right answer by luck. Even if the counters *were*
    forced to three - the printed final chapter - CR 704.5s still would not
    apply, because the qualifier is about chapter abilities and not about the
    number. Forcing them proves the immortality does not rest on the count
    happening to stay low."""
    scenario, saga = _mid_story()

    saga.add_counters("lore", 5)
    scenario.game.check_state_based_actions()

    assert saga.lore_counters == 7
    assert saga.zone is Zone.BATTLEFIELD


def test_mid_story_it_keeps_chapter_ones_colorless_mana_ability():
    """CR 611.2's continuous effect from a resolution, applied in layer 6
    (CR 613.1f) - after layer 4, so Blood Moon cannot reach it. Tapped for real
    through `CostPayment.tap_for_mana`, not merely read off a list."""
    scenario, saga = _mid_story()

    assert "{T}: Add {C}." in saga.granted_ability_texts

    payment = scenario.game.begin_activating(
        saga, _index_of(scenario, saga, "{T}: Add {C}."), "alice"
    )
    payment.tap_for_mana(saga, [Color.COLORLESS])

    assert payment.pool.floating == {Color.COLORLESS: 1}
    assert saga.tapped


def test_mid_story_it_also_gains_the_mountains_red_mana_ability():
    """The other half of the same permanent: CR 305.6 gives an object with the
    land type Mountain the intrinsic "{T}: Add {R}", so the Saga now offers
    *both* - a colourless one it was granted and a red one it is entitled to.
    """
    scenario, saga = _mid_story()

    assert "{T}: Add {R}." in _abilities(scenario, saga)

    payment = scenario.game.begin_activating(
        saga, _index_of(scenario, saga, "{T}: Add {R}."), "alice"
    )
    payment.tap_for_mana(saga, [Color.RED])

    assert payment.pool.floating == {Color.RED: 1}


def test_mid_story_it_still_makes_constructs():
    """Chapter II's grant is an *activated* ability with its own cost
    (CR 113.10a: "activation instructions ... become part of the ability that's
    added"), and it survives for the same layer-6 reason chapter I's does."""
    scenario, saga = _mid_story(extra_battlefield=["Sol Ring"])

    construct_maker = next(
        index
        for index, ability in enumerate(scenario.game.activated_abilities(saga))
        if "Construct" in ability.raw
    )
    (sol_ring,) = scenario.untapped_sources("Sol Ring")
    scenario.activate(saga, sol_ring, index=construct_maker)
    scenario.resolve_top()

    constructs = [p for p in scenario.game.battlefield if p.name == "Construct Token"]
    assert len(constructs) == 1
    # The Construct's own "+1/+1 for each artifact you control" is a live
    # sublayer 7c count (CR 613.4c) - itself and Sol Ring, on a printed 0/0.
    characteristics = scenario.game.characteristics_of(constructs[0])
    assert (characteristics.power, characteristics.toughness) == (2, 2)
    assert saga.tapped, "the {2}, {T} cost tapped the Saga along with the mana"


