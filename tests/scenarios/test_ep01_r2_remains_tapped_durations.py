"""Effects that last "for as long as this <permanent> remains tapped".

CR 611.2b: "Some continuous effects generated by the resolution of a spell or
ability have durations that are tied to a specific condition. ... If the
condition is already false at the time the effect would begin, the effect
does nothing. ... It doesn't start and immediately stop again, and it doesn't
last forever." Here the condition is the *source's* tapped status: each of
these permanents prints "You may choose not to untap ~ during your untap step"
(CR 502.3), and untapping it - or it leaving (CR 400.7) - ends the effect.

- Deserter's Quarters / Rust Tick / Entrancing Lyre: "Tap target <creature|
  artifact>. It doesn't untap during its controller's untap step for as long
  as this <artifact|creature> remains tapped."
- Vedalken Shackles: "Gain control of target creature with power less than or
  equal to the number of Islands you control for as long as this artifact
  remains tapped." (layer 2, CR 613.1b)
- Hisoka's Guard: "Target creature you control other than this creature has
  shroud for as long as this creature remains tapped." (layer 6)
- Giant Oyster: the lock, plus "at the beginning of each of your draw steps,
  put a -1/-1 counter on that creature. When this creature leaves the
  battlefield or becomes untapped, remove all -1/-1 counters from the
  creature."
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Zone
from magic_cards_model.support import card_support
from tests.cards import card
from tests.scenarios.harness import Scenario


def _board(alice, bob=None):
    scenario = (
        Scenario()
        .player("alice", battlefield=alice, library=["Island"] * 10)
        .player("bob", battlefield=bob or [], library=["Island"] * 10)
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    return scenario


def _advance(scenario) -> None:
    if scenario.game.turn.step is Step.UNTAP:
        scenario.advance()  # CR 502.4: triggers wait for the upkeep
        return
    scenario.game.put_triggers_on_stack()
    while scenario.game.stack:
        scenario.pass_until_resolved()
        scenario.game.put_triggers_on_stack()
    scenario.advance()


def _past_untap_of(scenario, username, *, keep_tapped=None):
    """Run turns until `username`'s untap step has happened. `keep_tapped`
    is the source whose controller chooses not to untap it."""
    game = scenario.game
    start = game.turn.turns_taken
    if keep_tapped is not None:
        scenario.will_take_the_may(True, username=username, source=keep_tapped)
    while not (game.turn.active_player == username and game.turn.turns_taken > start):
        _advance(scenario)
    while game.turn.step is Step.UNTAP:
        _advance(scenario)


def _activate(scenario, name, *mana, targets, index=0):
    source = scenario.find(name, Zone.BATTLEFIELD, "alice")
    scenario.activate(source, *mana, targets=targets, index=index)
    scenario.pass_until_resolved()
    return source


# -- tap and lock --------------------------------------------------------------


def test_deserters_quarters_lock_holds_while_it_stays_tapped():
    scenario = _board(["Deserter's Quarters"] + ["Plains"] * 6, ["Hill Giant"])
    giant = scenario.find("Hill Giant", Zone.BATTLEFIELD, "bob")
    _activate(
        scenario,
        "Deserter's Quarters",
        *scenario.untapped_sources(*["Plains"] * 6),
        targets=[giant],
    )
    assert giant.tapped

    _past_untap_of(scenario, "bob")
    assert giant.tapped


def test_deserters_quarters_lock_ends_when_it_untaps():
    scenario = _board(["Deserter's Quarters"] + ["Plains"] * 6, ["Hill Giant"])
    giant = scenario.find("Hill Giant", Zone.BATTLEFIELD, "bob")
    quarters = _activate(
        scenario,
        "Deserter's Quarters",
        *scenario.untapped_sources(*["Plains"] * 6),
        targets=[giant],
    )
    _past_untap_of(scenario, "alice")  # alice lets it untap
    assert not quarters.tapped

    _past_untap_of(scenario, "bob")
    assert not giant.tapped


def test_rust_tick_locks_an_artifact_and_kept_tapped_keeps_it_locked():
    scenario = _board(["Rust Tick", "Plains"], ["Ornithopter"])
    thopter = scenario.find("Ornithopter", Zone.BATTLEFIELD, "bob")
    _activate(scenario, "Rust Tick", *scenario.untapped_sources("Plains"), targets=[thopter])
    _past_untap_of(scenario, "bob")
    _past_untap_of(scenario, "alice", keep_tapped="Rust Tick")
    _past_untap_of(scenario, "bob")
    assert thopter.tapped


def test_entrancing_lyre_locks_a_creature_with_power_x_or_less():
    scenario = _board(["Entrancing Lyre", "Plains", "Plains"], ["Grizzly Bears"])
    bears = scenario.find("Grizzly Bears", Zone.BATTLEFIELD, "bob")
    lyre = scenario.find("Entrancing Lyre", Zone.BATTLEFIELD, "alice")
    scenario.activate(
        lyre, *scenario.untapped_sources("Plains", "Plains"), targets=[bears], x_value=2
    )
    scenario.pass_until_resolved()
    _past_untap_of(scenario, "bob")
    assert bears.tapped


def test_the_lock_ends_when_the_source_leaves_the_battlefield():
    scenario = _board(["Deserter's Quarters"] + ["Plains"] * 6, ["Hill Giant"])
    giant = scenario.find("Hill Giant", Zone.BATTLEFIELD, "bob")
    quarters = _activate(
        scenario,
        "Deserter's Quarters",
        *scenario.untapped_sources(*["Plains"] * 6),
        targets=[giant],
    )
    scenario.game.put_into_graveyard(quarters)
    _past_untap_of(scenario, "bob")
    assert not giant.tapped


