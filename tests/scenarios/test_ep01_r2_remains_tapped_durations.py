def test_vedalken_shackles_steals_while_tapped_and_returns_on_untap():
    scenario = _board(["Vedalken Shackles", "Island", "Island", "Island"], ["Grizzly Bears"])
    bears = scenario.find("Grizzly Bears", Zone.BATTLEFIELD, "bob")
    shackles = _activate(
        scenario,
        "Vedalken Shackles",
        *scenario.untapped_sources("Island", "Island"),
        targets=[bears],
    )
    assert scenario.game.controller_of(bears).username == "alice"

    _past_untap_of(scenario, "bob")
    _past_untap_of(scenario, "alice", keep_tapped="Vedalken Shackles")
    assert scenario.game.controller_of(bears).username == "alice"

    shackles.untap()
    assert scenario.game.controller_of(bears).username == "bob"


def test_vedalken_shackles_cannot_target_power_above_your_island_count():
    scenario = _board(["Vedalken Shackles", "Island", "Island"], ["Hill Giant"])
    giant = scenario.find("Hill Giant", Zone.BATTLEFIELD, "bob")
    shackles = scenario.find("Vedalken Shackles", Zone.BATTLEFIELD, "alice")
    (candidates,) = scenario.game.legal_targets(shackles, "alice", ability_index=0)
    assert giant.id not in {getattr(t, "id", None) for t in candidates}
    bears_board = _board(["Vedalken Shackles", "Island", "Island"], ["Grizzly Bears"])
    bears = bears_board.find("Grizzly Bears", Zone.BATTLEFIELD, "bob")
    own = bears_board.find("Vedalken Shackles", Zone.BATTLEFIELD, "alice")
    (candidates,) = bears_board.game.legal_targets(own, "alice", ability_index=0)
    assert bears.id in {getattr(t, "id", None) for t in candidates}


