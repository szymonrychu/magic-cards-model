def test_hisokas_guard_grants_shroud_only_while_it_stays_tapped():
    scenario = _board(["Hisoka's Guard", "Island", "Island", "Grizzly Bears"])
    bears = scenario.find("Grizzly Bears", Zone.BATTLEFIELD, "alice")
    guard = _activate(
        scenario, "Hisoka's Guard", *scenario.untapped_sources("Island", "Island"), targets=[bears]
    )
    assert scenario.game.shroud_refusal(bears) is not None
    guard.untap()
    assert scenario.game.shroud_refusal(bears) is None


# -- Giant Oyster ----------------------------------------------------------------


def test_giant_oyster_shrinks_its_target_each_draw_step_and_then_restores_it():
    scenario = _board(["Giant Oyster"], ["Hill Giant"])
    giant = scenario.find("Hill Giant", Zone.BATTLEFIELD, "bob")
    giant.tapped = True
    oyster = _activate(scenario, "Giant Oyster", targets=[giant])

    _past_untap_of(scenario, "bob")
    assert giant.tapped
    _past_untap_of(scenario, "alice", keep_tapped="Giant Oyster")
    while scenario.game.turn.step is not Step.PRECOMBAT_MAIN:
        _advance(scenario)
    assert giant.counters["-1/-1"] == 1

    _past_untap_of(scenario, "alice")  # Oyster untaps: the counters go
    scenario.game.put_triggers_on_stack()
    while scenario.game.stack:
        scenario.pass_until_resolved()
    assert not oyster.tapped
    assert giant.counters["-1/-1"] == 0


def test_every_remains_tapped_card_reads_handled():
    for name in (
        "Deserter's Quarters",
        "Rust Tick",
        "Entrancing Lyre",
        "Vedalken Shackles",
        "Hisoka's Guard",
        "Giant Oyster",
    ):
        support = card_support(card(name))
        assert support.status == "handled", (
            name,
            [c for c in support.clauses if c.status != "handled"],
        )
