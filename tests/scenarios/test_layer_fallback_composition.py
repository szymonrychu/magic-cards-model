"""Scenario: a spell or ability whose text mixes a continuous-effect (CR
611.2) sentence - a pump, a keyword grant, a base P/T set - with a sibling
sentence that is not one of those shapes, in the same resolution.

`_is_layer_effect_text` (`machines/effects.py`) decides whether a whole
piece of resolving text should route to `create_continuous_effect`/
`create_continuous_effect_of_ability` by asking whether *any* sentence in it
looks like a layer shape - right for routing, wrong for what used to happen
next: the *entire* text, sibling sentences included, was handed to that
single dispatcher, which reads `parsed_layer_effects` and silently skips any
sentence that is not itself a layer shape (by design - see its own
docstring, since that skip is correct when it is reading a permanent's whole
oracle text off the battlefield sweep). Run from a *resolving* spell's own
multi-sentence effect text instead, the same silent skip drops a second,
independent instruction with no trace at all: Academic Ascent's own "Empower
Jace 2." never reached any parser, and the card scored `handled` anyway.

`_compose_layer_effect_with_remainder` still lets the layer sentence run
through the same dispatcher unchanged, but now also asks
`parse_mixed_effect_for_spell`/`parse_mixed_effect` to read whatever is left,
and runs it in the printed order (CR 608.2c) when it can - Blazing
Crescendo's own trailing impulse-draw sentence is fully readable this way, so
the whole card now resolves. When the remainder cannot be read, this records
a `LayerRemainderNotice` instead of losing it with no trace.

Every CR number below was looked up with `knowledge_search(q="...",
type="rules")` (and cross-checked with `mise run rules:find`, on-disk CR
effective 2026-09-25) in the session that wrote this file:

- **CR 611.2** - "A continuous effect may be generated by the resolution of a
  spell or ability" - what the layer sentence half of each of these cards is.
- **CR 608.2c** - "The controller of the spell or ability follows its
  instructions in the order written on the spell or ability (or as modified
  by other effects) ..." - why the pump/grant runs before the sibling
  instruction, in printed order, rather than in some other order.
- **CR 701.13a/701.13d** - exiling a card and the temporary permission to
  play it from exile, Blazing Crescendo's own impulse-draw half.
- **CR 701.18a** - untapping a permanent, Tethermage's Advantage's own
  "Untap it."

Academic Ascent's own "Empower Jace 2." was not itself read when this wave
wrote it (CR 701.71's keyword action was a different wave's work at the
time), so it originally proved the pump half ran and the unread half was
recorded rather than dropped. Empower Jace has since landed and reads
Academic Ascent's own sentence whole - see
`test_empower_jace.py::test_academic_ascent_composes_the_pump_with_the_empower_second_sentence`
for that composition now that both halves read - so this file's own proof
of the composition mechanism rests on Blazing Crescendo, Tethermage's
Advantage, and Artifist Acumen instead.
"""

from magic_cards_model.machines import Step
from magic_cards_model.machines.casting import play_permissions_on
from magic_cards_model.machines.combat import Keyword, has_keyword
from magic_cards_model.models import Zone
from tests.scenarios.harness import Scenario


def test_blazing_crescendo_pumps_and_grants_the_full_impulse_draw_permission():
    """`Target creature gets +3/+1 until end of turn. Exile the top card of
    your library. Until the end of your next turn, you may play that card.`

    Both halves are readable on their own once composed: the pump is CR
    611.2's layer shape, and the exile-then-play sentence pair is
    `_merge_exile_top_then_play_until_next_turn_clauses`'s own shape (Wrenn's
    Resolve, Reckless Impulse) - this card's only gap there was the implicit
    singular "the top card" (no explicit count word). Composing the two
    halves is what used to throw the whole second half away, since the first
    sentence alone routed the entire text to `create_continuous_effect`.
    """
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Blazing Crescendo"],
            battlefield=["Mountain", "Mountain", "Grizzly Bears"],
            library=["Lightning Bolt", "Mountain", "Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    alice = scenario.game.player("alice")
    top_of_library = alice.library[0]

    scenario.cast_and_resolve(
        "Blazing Crescendo", *scenario.untapped_sources("Mountain", "Mountain"), targets=[bears]
    )

    assert scenario.game.characteristics_of(bears).power_toughness == (2 + 3, 2 + 1)
    assert top_of_library.zone is Zone.EXILE
    assert scenario.game.layer_remainder_notices == []
    assert play_permissions_on(scenario.game, top_of_library) != []


def test_tethermages_advantage_pumps_grants_reach_and_untaps():
    """`Target creature gets +2/+2 and gains reach until end of turn. Untap
    it.` - the object-anaphor rider family (`_parse_object_anaphor_clause_
    pair`) gains an "Untap it." rider (CR 701.18a): a tapped creature comes
    back untapped in the same instruction that pumped it.
    """
    scenario = (
        Scenario()
        .player("alice", hand=["Tethermage's Advantage"], battlefield=["Forest", "Grizzly Bears"])
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    bears.tap()
    assert bears.tapped

    scenario.cast_and_resolve(
        "Tethermage's Advantage", *scenario.untapped_sources("Forest"), targets=[bears]
    )

    assert scenario.game.characteristics_of(bears).power_toughness == (2 + 2, 2 + 2)
    assert has_keyword(bears, Keyword.REACH, scenario.game)
    assert not bears.tapped
    assert scenario.game.layer_remainder_notices == []


def test_artifist_acumen_grants_first_strike_to_the_team_and_draws_a_card():
    """Off-set generality proof, not Reality Fracture and not in this wave's
    own reported deck: "Creatures you control gain first strike until end of
    turn. Draw a card." - a *group* keyword grant with no power/toughness
    change at all (`_MASS_PUMP_UNTIL_EOT_RE` used to require the "get +N/+N"
    half; a pure keyword grant like this one never matched it, so
    `_is_layer_effect_text` answered False and this sentence was not even
    recognised as a layer shape) sitting beside an ordinary player clause.
    Both halves now run, composed in printed order (CR 608.2c).
    """
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Artifist Acumen"],
            battlefield=["Mountain", "Grizzly Bears", "Grizzly Bears"],
            library=["Lightning Bolt"],
        )
        .player("bob", battlefield=["Grizzly Bears"])
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    alice_bears = scenario.creatures("Grizzly Bears", "Grizzly Bears", username="alice")
    bobs_bear = scenario.creature("Grizzly Bears", "bob")
    alice = scenario.game.player("alice")
    hand_before = len(alice.hand)

    scenario.cast_and_resolve("Artifist Acumen", *scenario.untapped_sources("Mountain"))

    for bear in alice_bears:
        assert has_keyword(bear, Keyword.FIRST_STRIKE, scenario.game)
    assert not has_keyword(bobs_bear, Keyword.FIRST_STRIKE, scenario.game)
    # The card itself leaves the hand to be cast, and the "Draw a card."
    # half puts one back - net unchanged from `hand_before`.
    assert len(alice.hand) == hand_before
    assert scenario.game.layer_remainder_notices == []
