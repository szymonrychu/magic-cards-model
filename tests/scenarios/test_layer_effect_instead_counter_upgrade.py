"""Scenario: a resolving spell or ability whose own text is a CR 611.2
continuous-effect (a pump) followed by "If `<condition>`, put `<n>` `<kind>`
counter(s) on it/that creature instead." - CR 608.2c's own worked example
("later text on the card may modify the meaning of earlier text ... Counter
target spell. If that spell is countered this way, put it on top of its
owner's library instead of into its owner's graveyard.") applied to a pump: at
resolution, either the layer pump runs, or - when the condition holds - the
counter(s) land on the same object(s) the pump would have affected. Never
both, never neither.

`_compose_layer_effect_with_remainder_for_ability` (`machines/effects.py`)
used to treat every sibling sentence beside a genuine layer sentence the same
way: run the layer effect, then try to read the remainder as an *additional*
instruction through `parse_mixed_effect`. Desperate Futurescribe's own
"instead" sentence is not additional - it *replaces* the pump - and
`parse_mixed_effect` has no shape for "if <condition>, put N counters on it
instead", so the card fell through to a `LayerRemainderNotice`: the pump
always ran and the permanent-counter upgrade was silently dropped even when
the condition was true.

`_parse_layer_counter_instead_upgrade` now reads that shape ahead of the
ordinary remainder composer and asks `Game.condition_holds` (already correct
for every condition it reads, including "you've scried or surveilled this
turn" - see `test_scry_or_surveil_trigger.py`) which branch applies. `None`
(a condition this wave does not read at all) still fails closed the same way
an unreadable remainder always has: the pump runs and a notice records the
untried swap.

Verified this session with `mise run rules:find` (on-disk CR effective
2026-09-25):

- **CR 608.2c** - "later text on the card may modify the meaning of earlier
  text", with the Comprehensive Rules' own worked example of exactly this
  shape (a counter-then-"instead" pair), which is why this is read as
  CR 608.2c's ordinary instruction order rather than as a CR 614 replacement
  effect - there is no continuous replacement effect watching for a future
  event here, only two branches of one instruction on one resolving object.
- **CR 611.2/611.2a** - the pump itself, a continuous effect generated by a
  resolving ability, lasting until end of turn.
- **CR 122.1/122.1a** - a +1/+1 counter, and that CR 122.1a's separate
  power/toughness counters are not the same object as a temporary pump.
- **CR 701.22a/701.25a** - scry and surveil, the condition Desperate
  Futurescribe's own upgrade reads (`Game.turn_facts`, `test_scry_or_
  surveil_trigger.py`).
"""

from magic_cards_model.machines import Step
from magic_cards_model.models.card_state import Counter
from tests.scenarios.harness import Scenario


def computed(scenario: Scenario):
    """The board with static abilities and stored durational effects applied."""
    return scenario.game.continuous_effects.board(scenario.game.battlefield)


def test_desperate_futurescribe_pumps_without_scry_or_surveil():
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=["Desperate Futurescribe", "Grizzly Bears"],
            library=["Mountain"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.choose_trigger_targets("Desperate Futurescribe", [bears])
    scenario.advance()
    assert scenario.step is Step.BEGINNING_OF_COMBAT
    scenario.pass_until_resolved()

    assert computed(scenario).of(bears).power_toughness == (3, 3), "a 2/2 plus a temporary +1/+1"
    assert bears.counter_count(Counter.PLUS_ONE) == 0


def test_desperate_futurescribe_upgrades_to_a_permanent_counter_after_scrying():
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=["Desperate Futurescribe", "Grizzly Bears"],
            library=["Mountain", "Forest"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.scry_keeping_everything_on_top(username="alice")
    scenario.game.scry("alice", 1, source="Desperate Futurescribe")
    scenario.game.put_triggers_on_stack()
    assert scenario.stack_names() == []  # scrying itself is not the trigger

    scenario.choose_trigger_targets("Desperate Futurescribe", [bears])
    scenario.advance()
    assert scenario.step is Step.BEGINNING_OF_COMBAT
    scenario.pass_until_resolved()

    assert bears.counter_count(Counter.PLUS_ONE) == 1, "the counter, not the temporary pump"
    assert computed(scenario).of(bears).power_toughness == (3, 3), (
        "the same +1/+1, now a lasting counter"
    )


def test_power_plant_worker_upgrades_to_two_counters_off_pool():
    """Off-pool generality proof: Power Plant Worker prints the identical
    shape with a different pump amount (+2/+2, not +1/+1), a different
    counter count (two, not one), a different condition (two named
    permanents controlled, not a turn fact), and no target at all - "this
    creature", not "that creature" - so this exercises
    `_parse_layer_counter_instead_upgrade` and `Game.condition_holds`'s new
    `_CONDITION_CONTROLS_NAMED_PAIR` branch on wording the parser was never
    built against."""
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=[
                "Power Plant Worker",
                "Mine Worker",
                "Tower Worker",
                "Plains",
                "Plains",
                "Plains",
            ],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    worker = scenario.creature("Power Plant Worker", "alice")
    scenario.activate(worker, *scenario.untapped_sources("Plains", "Plains", "Plains"))

    scenario.pass_until_resolved()

    assert worker.counter_count(Counter.PLUS_ONE) == 2
    assert computed(scenario).of(worker).power_toughness == (6, 6), (
        "base 4/4 plus two +1/+1 counters"
    )


