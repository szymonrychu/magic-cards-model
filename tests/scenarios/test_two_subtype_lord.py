def test_warg_rider_gives_its_orcs_and_goblins_menace():
    """Second printing of the reader: Orcish Spy is an Orc, Raging Goblin a
    Goblin, and both gain menace in layer 6; Grizzly Bears does not."""
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=["Warg Rider", "Orcish Spy", "Raging Goblin", "Grizzly Bears"],
        )
        .player("bob")
        .build()
    )
    orc = scenario.creature("Orcish Spy")
    goblin = scenario.creature("Raging Goblin")
    bears = scenario.creature("Grizzly Bears")

    assert has_keyword(orc, Keyword.MENACE, scenario.game)
    assert has_keyword(goblin, Keyword.MENACE, scenario.game)
    assert not has_keyword(bears, Keyword.MENACE, scenario.game)


def test_warg_riders_grant_skips_an_opponents_goblin():
    scenario = (
        Scenario()
        .player("alice", battlefield=["Warg Rider"])
        .player("bob", battlefield=["Raging Goblin"])
        .build()
    )
    theirs = scenario.creature("Raging Goblin", "bob")

    assert not has_keyword(theirs, Keyword.MENACE, scenario.game)
