"""Scenario: a lord over two creature types - "Other <A>s and <B>s you control".

Nightpack Ambusher: "Other Wolves and Werewolves you control get +1/+1."
Warg Rider (the second printing, Modern-legal, not in any api deck): "Other
Orcs and Goblins you control have menace."

CR 611.3a: "A continuous effect generated by a static ability isn't 'locked
in'; it applies at any given moment to whatever its text indicates." So the
group is re-read every time the board is computed - a Wolf that arrives later
is included, one that leaves is not, and the effect stops with its source.
The pump lands in layer 7c (CR 613.4c), the keyword grant in layer 6
(CR 613.1f).

The subtype words are printed plurals ("Wolves", "Werewolves") and are read
back to the type-line singular through `data/subtypes.canonical_subtype`, not
by stripping a trailing "s" - "Wolves" is not "Wolve".
"""

from magic_cards_model.machines import Step
from magic_cards_model.machines.combat import Keyword, has_keyword
from magic_cards_model.models import Zone
from magic_cards_model.models.token import token_copy_of
from tests.scenarios.harness import Scenario


def pt(scenario, state):
    chars = scenario.game.characteristics_of(state)
    return chars.power, chars.toughness


def printed(state):
    return int(state.card.power), int(state.card.toughness)


def plus(state, n):
    power, toughness = printed(state)
    return power + n, toughness + n


def test_both_named_types_get_the_pump_and_nothing_else_does():
    """Watchwolf is a Wolf, Edgar a Werewolf, Grizzly Bears neither."""
    scenario = (
        Scenario()
        .player(
            "alice",
            battlefield=[
                "Nightpack Ambusher",
                "Watchwolf",
                "Edgar, Moonlit Sovereign",
                "Grizzly Bears",
            ],
        )
        .player("bob")
        .build()
    )
    wolf = scenario.creature("Watchwolf")
    werewolf = scenario.creature("Edgar, Moonlit Sovereign")
    bears = scenario.creature("Grizzly Bears")

    assert pt(scenario, wolf) == plus(wolf, 1)
    assert pt(scenario, werewolf) == plus(werewolf, 1)
    assert pt(scenario, bears) == printed(bears)


def test_the_lord_does_not_pump_itself():
    """ "Other": Nightpack Ambusher is a Wolf, and is excluded by identity."""
    scenario = Scenario().player("alice", battlefield=["Nightpack Ambusher"]).player("bob").build()
    ambusher = scenario.creature("Nightpack Ambusher")

    assert pt(scenario, ambusher) == printed(ambusher)


def test_two_lords_pump_each_other_once():
    """Each Ambusher is an "other Wolf" to the second one - +1/+1 each, not +2/+2."""
    scenario = (
        Scenario()
        .player("alice", battlefield=["Nightpack Ambusher", "Nightpack Ambusher", "Watchwolf"])
        .player("bob")
        .build()
    )
    first, second = scenario.creatures("Nightpack Ambusher", "Nightpack Ambusher")
    wolf = scenario.creature("Watchwolf")

    assert pt(scenario, first) == plus(first, 1)
    assert pt(scenario, second) == plus(second, 1)
    assert pt(scenario, wolf) == plus(wolf, 2)


def test_an_opponents_wolf_is_not_pumped():
    """ "you control" - bob's Watchwolf is outside the group."""
    scenario = (
        Scenario()
        .player("alice", battlefield=["Nightpack Ambusher"])
        .player("bob", battlefield=["Watchwolf"])
        .build()
    )
    theirs = scenario.creature("Watchwolf", "bob")

    assert pt(scenario, theirs) == printed(theirs)


def test_a_wolf_token_that_arrives_later_is_pumped():
    """CR 611.3a: the group is whatever the text indicates now. A token copy
    of Watchwolf is a Wolf, created after the lord."""
    scenario = (
        Scenario()
        .player("alice", battlefield=["Nightpack Ambusher", "Watchwolf"])
        .player("bob")
        .build()
    )
    wolf = scenario.creature("Watchwolf")
    (token,) = token_copy_of(scenario.game, wolf, "alice")

    assert pt(scenario, token) == plus(wolf, 1)


def test_the_pump_stops_when_the_lord_leaves():
    """CR 611.3b: the effect applies only while its source is on the battlefield."""
    scenario = (
        Scenario()
        .player("alice", battlefield=["Nightpack Ambusher", "Watchwolf"])
        .player("bob")
        .build()
    )
    ambusher = scenario.creature("Nightpack Ambusher")
    wolf = scenario.creature("Watchwolf")
    assert pt(scenario, wolf) == plus(wolf, 1)

    scenario.game.put_into_graveyard(ambusher)

    assert ambusher.zone is Zone.GRAVEYARD
    assert pt(scenario, wolf) == printed(wolf)


def test_a_lord_cast_later_pumps_the_wolves_already_there():
    """The lord is the newcomer this time; flash, cast on bob's turn is not
    needed - the static applies from the moment it resolves."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Nightpack Ambusher"],
            battlefield=["Watchwolf", "Forest", "Forest", "Forest", "Forest"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    wolf = scenario.creature("Watchwolf")
    assert pt(scenario, wolf) == printed(wolf)

    sources = scenario.untapped_sources("Forest", "Forest", "Forest", "Forest")
    scenario.cast_and_resolve("Nightpack Ambusher", *sources)

    assert pt(scenario, wolf) == plus(wolf, 1)


