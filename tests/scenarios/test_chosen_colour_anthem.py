"""Scenario: "Creatures you control of the chosen color get +N/+N."

Caged Sun: "As this artifact enters, choose a color. / Creatures you control
of the chosen color get +1/+1." Heraldic Banner (the second printing, legal in
Modern, Pioneer and Standard, not in any api deck) prints the same subject
with +1/+0, and Hall of Triumph the same with +1/+1 on a legendary artifact.

CR 614.12a: "If a replacement effect that modifies how a permanent enters the
battlefield requires a choice, that choice is made before the permanent enters
the battlefield." The colour is recorded on `CardState.choice` as the artifact
enters and read back by the anthem.

CR 611.3a: "A continuous effect generated by a static ability isn't 'locked
in'; it applies at any given moment to whatever its text indicates." The
colour test is asked of each creature's *computed* colours (CR 105.2) every
time the board is computed, so a creature arriving later is included and the
bonus stops when the artifact leaves. The pump is layer 7c (CR 613.4c).
"""

from magic_cards_model.machines import Step
from magic_cards_model.models import Color, Zone
from tests.scenarios.harness import Scenario


def pt(scenario, state):
    chars = scenario.game.characteristics_of(state)
    return chars.power, chars.toughness


def printed(state):
    return int(state.card.power), int(state.card.toughness)


def shifted(state, power, toughness):
    base_power, base_toughness = printed(state)
    return base_power + power, base_toughness + toughness


def with_artifact(artifact, color, alice=(), bob=(), hand=()):
    scenario = (
        Scenario()
        .player("alice", hand=[artifact, *hand], battlefield=list(alice))
        .player("bob", battlefield=list(bob))
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    scenario.will_choose(color.value, source=artifact)
    permanent = scenario.put_onto_battlefield(artifact)
    return scenario, permanent


def test_caged_sun_pumps_only_creatures_of_the_chosen_colour():
    scenario, sun = with_artifact(
        "Caged Sun", Color.GREEN, alice=["Grizzly Bears", "Savannah Lions", "Memnite"]
    )
    bears = scenario.creature("Grizzly Bears")
    lions = scenario.creature("Savannah Lions")
    memnite = scenario.creature("Memnite")

    assert sun.choice is not None and sun.choice.value == Color.GREEN.value
    assert pt(scenario, bears) == shifted(bears, 1, 1)
    assert pt(scenario, lions) == printed(lions)
    assert pt(scenario, memnite) == printed(memnite), "colourless is no colour (CR 105.2c)"


def test_a_multicoloured_creature_with_the_chosen_colour_counts():
    """Watchwolf is green and white; choosing white still catches it."""
    scenario, _ = with_artifact("Caged Sun", Color.WHITE, alice=["Watchwolf", "Grizzly Bears"])
    wolf = scenario.creature("Watchwolf")
    bears = scenario.creature("Grizzly Bears")

    assert pt(scenario, wolf) == shifted(wolf, 1, 1)
    assert pt(scenario, bears) == printed(bears)


def test_an_opponents_creature_of_the_chosen_colour_is_not_pumped():
    scenario, _ = with_artifact(
        "Caged Sun", Color.GREEN, alice=["Grizzly Bears"], bob=["Grizzly Bears"]
    )
    theirs = scenario.creature("Grizzly Bears", "bob")
    mine = scenario.creature("Grizzly Bears", "alice")

    assert pt(scenario, mine) == shifted(mine, 1, 1)
    assert pt(scenario, theirs) == printed(theirs)


def test_a_creature_that_arrives_later_is_pumped():
    """CR 611.3a - the group is re-read, not fixed when the artifact entered."""
    scenario, _ = with_artifact("Caged Sun", Color.GREEN, hand=["Grizzly Bears"])

    bears = scenario.put_onto_battlefield("Grizzly Bears")

    assert pt(scenario, bears) == shifted(bears, 1, 1)


def test_the_bonus_stops_when_the_artifact_leaves():
    scenario, sun = with_artifact("Caged Sun", Color.GREEN, alice=["Grizzly Bears"])
    bears = scenario.creature("Grizzly Bears")
    assert pt(scenario, bears) == shifted(bears, 1, 1)

    scenario.game.put_into_graveyard(sun)

    assert sun.zone is Zone.GRAVEYARD
    assert pt(scenario, bears) == printed(bears)


def test_two_artifacts_with_different_colours_each_pump_their_own():
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Caged Sun", "Caged Sun"],
            battlefield=["Grizzly Bears", "Savannah Lions", "Watchwolf"],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    scenario.will_choose(Color.GREEN.value, source="Caged Sun")
    scenario.put_onto_battlefield("Caged Sun")
    scenario.will_choose(Color.WHITE.value, source="Caged Sun")
    scenario.put_onto_battlefield("Caged Sun")
    bears = scenario.creature("Grizzly Bears")
    lions = scenario.creature("Savannah Lions")
    wolf = scenario.creature("Watchwolf")

    assert pt(scenario, bears) == shifted(bears, 1, 1)
    assert pt(scenario, lions) == shifted(lions, 1, 1)
    assert pt(scenario, wolf) == shifted(wolf, 2, 2), "green and white: both apply"


def test_the_choice_made_when_cast_is_the_one_read():
    """Cast rather than put: the choice is still made as it enters."""
    scenario = (
        Scenario()
        .player(
            "alice",
            hand=["Caged Sun"],
            battlefield=["Grizzly Bears", "Savannah Lions", *["Plains"] * 6],
        )
        .player("bob")
        .build()
    )
    scenario.start_at(Step.PRECOMBAT_MAIN)
    scenario.will_choose(Color.WHITE.value, source="Caged Sun")
    sources = scenario.untapped_sources(*["Plains"] * 6)
    scenario.cast_and_resolve("Caged Sun", *sources)
    bears = scenario.creature("Grizzly Bears")
    lions = scenario.creature("Savannah Lions")

    assert pt(scenario, lions) == shifted(lions, 1, 1)
    assert pt(scenario, bears) == printed(bears)


