def test_heraldic_banner_gives_plus_one_power_to_the_chosen_colour():
    scenario, _ = with_artifact(
        "Heraldic Banner", Color.RED, alice=["Raging Goblin", "Grizzly Bears"]
    )
    goblin = scenario.creature("Raging Goblin")
    bears = scenario.creature("Grizzly Bears")

    assert pt(scenario, goblin) == shifted(goblin, 1, 0)
    assert pt(scenario, bears) == printed(bears)


def test_hall_of_triumph_reads_the_same_subject():
    scenario, _ = with_artifact(
        "Hall of Triumph", Color.WHITE, alice=["Savannah Lions", "Grizzly Bears"]
    )
    lions = scenario.creature("Savannah Lions")
    bears = scenario.creature("Grizzly Bears")

    assert pt(scenario, lions) == shifted(lions, 1, 1)
    assert pt(scenario, bears) == printed(bears)
