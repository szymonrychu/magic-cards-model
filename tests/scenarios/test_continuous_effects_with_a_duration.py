"""Scenario: a continuous effect created by a resolving spell or ability (CR 611.2).

CR 611.2: "A continuous effect may be generated by the resolution of a spell or
ability." That is a different animal from the static-ability effects of
`test_static_abilities.py`. A static ability's effect exists exactly while its
source is on the battlefield with the ability (CR 611.3b), so it can be rebuilt
from the board every time and never stored. This kind outlives the resolution
that made it, so somebody has to write it down:

- **CR 611.2a** - "A continuous effect generated by the resolution of a spell or
  ability lasts as long as stated by the spell or ability creating it (such as
  'until end of turn')."
- **CR 611.2b** - "Some continuous effects generated by the resolution of a
  spell or ability have durations worded 'for as long as . . . .' If the 'for as
  long as' duration never starts, the effect does nothing."
- **CR 611.2c** - the set of objects the effect applies to is fixed when the
  effect begins, and never recomputed.
- **CR 613.7b** - "A continuous effect generated by the resolution of a spell or
  ability receives a timestamp at the time it's created", which is what orders
  it against the static effects already in play (CR 613.7a).
- **CR 514.2** - the moment "until end of turn" ends. Not the end step: CR 500.5b
  sends the duration to CR 514.2, and CR 514.2 ends every such effect in the
  cleanup step, simultaneously with wiping marked damage, as the turn-based
  action CR 703.4p describes.

`machines/layers.py` holds the store, `ContinuousEffects`. `models/game.py` does
not have a field for one yet - it is owned elsewhere - so `hold_effects` below
attaches the store the way that one-line field would, and the engine finds it
through `machines/effects.py`'s `continuous_effects(game)`. Everything else in
these tests is the real engine: real printings, real casting, real resolution.

Every CR number in this file was looked up with `knowledge_search(type="rules")`
in the session that wrote it.
"""

from magic_cards_model.machines import Step
from magic_cards_model.machines.layers import ContinuousEffects, Duration, compute_board
from magic_cards_model.models import Zone
from tests.scenarios.harness import Scenario


def hold_effects(scenario) -> ContinuousEffects:
    """Give the game a store of durational continuous effects, and stamp the board.

    Stands in for the one field `models/game.py` needs::

        continuous_effects: ContinuousEffects = Field(default_factory=ContinuousEffects)

    `note` stamps the opening battlefield in order, because CR 613.7a gives a
    static ability's effect the timestamp of the object it is on - so a spell
    resolving afterwards is correctly newer than everything already there.
    """
    store = ContinuousEffects()
    store.note(scenario.game.battlefield)
    object.__setattr__(scenario.game, "continuous_effects", store)
    return store


def computed(scenario, store: ContinuousEffects):
    """The board with static abilities and stored durational effects applied."""
    return store.board(scenario.game.battlefield, game=scenario.game)


def pump_board() -> Scenario:
    """Alice with a Giant Growth and enough green for it, and a Bear to aim it at."""
    return (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Giant Growth"],
            library=["Forest"],
            battlefield=["Grizzly Bears", "Forest", "Forest"],
        )
        .player("bob", library=["Island"], battlefield=["Island"])
    )


