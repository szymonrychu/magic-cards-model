def test_giant_growth_pumps_the_creature_it_resolved_on():
    """CR 611.2, CR 613.4c: "Target creature gets +3/+3 until end of turn."

    The spell resolves and leaves nothing behind on the stack, but the board it
    left behind is different: the effect is stored and applies in sublayer 7c
    every time the board is computed (CR 613.5).
    """
    scenario = pump_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    bears = scenario.creature("Grizzly Bears", "alice")
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    growth = scenario.cast_and_resolve("Giant Growth", forest, targets=[bears])

    assert growth.zone is Zone.GRAVEYARD, "the spell is gone; its effect is not"
    assert computed(scenario, store).of(bears).power_toughness == (5, 5)


def test_the_effect_applies_only_to_the_object_it_resolved_on():
    """CR 611.2c: the set of objects is determined when the effect begins.

    Two Grizzly Bears are two objects. The one the spell targeted is pumped and
    the other is not, and no amount of recomputing the board changes which.
    """
    scenario = (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            hand=["Giant Growth"],
            library=["Forest"],
            battlefield=["Grizzly Bears", "Grizzly Bears", "Forest"],
        )
        .build()
    )
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    pumped, spared = scenario.creatures("Grizzly Bears", "Grizzly Bears", username="alice")
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Giant Growth", forest, targets=[pumped])

    board = computed(scenario, store)
    assert board.of(pumped).power_toughness == (5, 5)
    assert board.of(spared).power_toughness == (2, 2)


