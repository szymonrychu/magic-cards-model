def test_the_pump_survives_the_end_step():
    """CR 500.5b: "until end of turn" is not "until the end step".

    The end step is a step like any other; the duration is sent to CR 514.2,
    which lives one step later. A creature pumped in the precombat main phase is
    still pumped while the end step's priority round is running, which is what
    makes an end-step pump spell a real play.
    """
    scenario = pump_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    bears = scenario.creature("Grizzly Bears", "alice")
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Giant Growth", forest, targets=[bears])

    scenario.start_at(Step.END_STEP)

    assert computed(scenario, store).of(bears).power_toughness == (5, 5)


def test_the_pump_wears_off_in_the_cleanup_step():
    """CR 514.2 and CR 703.4p: the moment the duration ends.

    "All damage marked on permanents ... is removed and all 'until end of turn'
    and 'this turn' effects end. This turn-based action happens immediately
    after the active player discards." `ContinuousEffects.end_the_turn` is that
    action; `Game.remove_all_damage` is its other half.
    """
    scenario = pump_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    bears = scenario.creature("Grizzly Bears", "alice")
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Giant Growth", forest, targets=[bears])

    scenario.start_at(Step.CLEANUP)
    ended = store.end_the_turn(scenario.game)

    assert [effect.duration for effect in ended] == [Duration.UNTIL_END_OF_TURN]
    assert store.effects == []
    assert computed(scenario, store).of(bears).power_toughness == (2, 2)


def test_reaching_the_cleanup_step_ends_the_effect_by_itself():
    """CR 703.3: a turn-based action happens on its own, with nobody choosing it.

    The engine already does the CR 703.4p half that wipes marked damage when
    `advance` reaches the cleanup step. The half of the same simultaneous event
    that ends "until end of turn" effects has nowhere to reach from.
    """
    scenario = pump_board().automatic_turn_based_actions().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    bears = scenario.creature("Grizzly Bears", "alice")
    (forest,) = scenario.untapped_sources("Forest", username="alice")
    scenario.cast_and_resolve("Giant Growth", forest, targets=[bears])

    scenario.start_at(Step.END_STEP)
    scenario.advance()  # cleanup

    assert computed(scenario, store).of(bears).power_toughness == (2, 2)


