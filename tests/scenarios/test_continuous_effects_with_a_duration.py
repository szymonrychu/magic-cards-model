def tidebinder_board() -> Scenario:
    """Alice with Vampiric Rites to switch off; Bob holding Tishana's Tidebinder.

    Vampiric Rites is a permanent with an activated ability, so "loses all
    abilities" is something the board can be asked about: the ability line is
    gone from its computed characteristics.
    """
    return (
        Scenario()
        .manual_turn_based_actions()
        .player(
            "alice",
            library=["Forest"],
            battlefield=["Vampiric Rites", "Swamp", "Swamp", "Grizzly Bears"],
        )
        .player(
            "bob",
            hand=["Tishana's Tidebinder"],
            library=["Forest"],
            battlefield=["Island", "Island", "Island"],
        )
    )


RITES_ABILITY = "{1}{B}, Sacrifice a creature: You gain 1 life and draw a card."


def test_the_permanent_loses_its_abilities_while_the_tidebinder_is_there():
    """CR 611.2b and CR 613.1f: "for as long as this creature remains on the battlefield".

    The effect is created here rather than by the Tidebinder's own trigger,
    because that trigger cannot reach its effect at all: `Game.resolve_target`
    only ever finds a `CardState`, so a target pointing at an ability resolves
    to nothing and CR 608.2b removes the trigger first. That gap has its own
    xfail below and in `tests/scenarios/test_countering_an_ability.py`. What is
    under test here is the duration, and the effect built is the registry's own.
    """
    scenario = tidebinder_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    scenario.pass_priority("alice")  # Tidebinder has flash, so Bob may act here
    islands = scenario.untapped_sources("Island", "Island", "Island", username="bob")
    tidebinder = scenario.cast_and_resolve("Tishana's Tidebinder", *islands, username="bob")
    rites = scenario.creature("Vampiric Rites", "alice")

    # `ContinuousEffects.create` mints the effect's own id with no `Game`
    # method's `_id_allocator_scope` open around it here.
    with scenario.game._id_allocator_scope():  # noqa: SLF001
        created = store.create(tidebinder, targets=[rites], game=scenario.game)
    assert created, "the duration has started"
    assert not computed(scenario, store).of(rites).has_ability(RITES_ABILITY)


def test_the_abilities_come_back_when_the_tidebinder_leaves():
    """The duration stops running, so the effect stops applying (CR 611.2b).

    Unlike "until end of turn", this one is not ended by a turn-based action -
    it is a question asked afresh every time the board is computed (CR 613.5),
    which is why bouncing the Tidebinder undoes it immediately.
    """
    scenario = tidebinder_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    scenario.pass_priority("alice")  # Tidebinder has flash, so Bob may act here
    islands = scenario.untapped_sources("Island", "Island", "Island", username="bob")
    tidebinder = scenario.cast_and_resolve("Tishana's Tidebinder", *islands, username="bob")
    rites = scenario.creature("Vampiric Rites", "alice")
    with scenario.game._id_allocator_scope():  # noqa: SLF001
        store.create(tidebinder, targets=[rites], game=scenario.game)

    scenario.game.destroy(tidebinder)

    assert tidebinder.zone is Zone.GRAVEYARD
    assert computed(scenario, store).of(rites).has_ability(RITES_ABILITY)


def test_an_effect_whose_duration_never_starts_does_nothing():
    """CR 611.2b, second sentence, word for word.

    The Tidebinder is answered in response to its own trigger, so by the time
    the trigger would resolve the creature is already in the graveyard. The
    "for as long as this creature remains on the battlefield" duration never
    starts, so the effect is not created at all - not created-and-immediately-
    expired, which would come back if the creature ever returned.
    """
    scenario = tidebinder_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    scenario.pass_priority("alice")  # Tidebinder has flash, so Bob may act here
    islands = scenario.untapped_sources("Island", "Island", "Island", username="bob")
    tidebinder = scenario.cast_and_resolve("Tishana's Tidebinder", *islands, username="bob")
    rites = scenario.creature("Vampiric Rites", "alice")
    scenario.game.destroy(tidebinder)

    with scenario.game._id_allocator_scope():  # noqa: SLF001
        assert store.create(tidebinder, targets=[rites], game=scenario.game) == []
    assert store.effects == []
    assert computed(scenario, store).of(rites).has_ability(RITES_ABILITY)


def test_an_expired_for_as_long_as_effect_is_swept_up_at_end_of_turn():
    """Housekeeping, not a rule: nothing can restart a stopped duration.

    CR 611.2b only speaks about a duration that never starts. One that has
    started and stopped is simply over, so `end_the_turn` drops it along with
    the "until end of turn" effects rather than leaving it to be re-asked
    forever.
    """
    scenario = tidebinder_board().build()
    store = hold_effects(scenario)
    scenario.start_at(Step.PRECOMBAT_MAIN)

    scenario.pass_priority("alice")  # Tidebinder has flash, so Bob may act here
    islands = scenario.untapped_sources("Island", "Island", "Island", username="bob")
    tidebinder = scenario.cast_and_resolve("Tishana's Tidebinder", *islands, username="bob")
    rites = scenario.creature("Vampiric Rites", "alice")
    with scenario.game._id_allocator_scope():  # noqa: SLF001
        store.create(tidebinder, targets=[rites], game=scenario.game)
    scenario.game.destroy(tidebinder)

    assert store.active(scenario.game) == []
    assert store.end_the_turn(scenario.game)
    assert store.effects == []


