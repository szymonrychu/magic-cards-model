"""Scenario: what "you've put one or more counters on ... this turn" remembers.

Per-turn counter-placement history (CR 122.6), read by static abilities (CR
604.2, CR 611.3a) and by a resolving ability:

- Beast, Erudite Aerialist: "As long as you've put one or more +1/+1 counters
  on Beast this turn, he has flying."
- Kid Loki: "Each creature you control that you've put one or more +1/+1
  counters on this turn has hexproof."
- Iridescent Hornbeetle (M21, not a listed card and not in a deck): "At the
  beginning of your end step, create a 1/1 green Insect creature token for
  each +1/+1 counter you've put on creatures under your control this turn." -
  the same `Game.counters_put_this_turn` ledger, counted rather than asked
  about. The "as long as ..." and "each creature ... that you've put" static
  wordings are printed only on Marvel Super Heroes cards, so Beast and Kid
  Loki prove each other's reader (see `MEMORY.md`).

And the plain counter-gated grant, which needs no history:

- Training Regimen: "Creatures you control with +1/+1 counters on them have
  trample." and Badgermole (TLA, not listed, not in a deck), the identical
  sentence.

Every CR number here was looked up with `mise run rules:find` in the session
that wrote this file:

- **CR 122.6** - counters being put on an object, on the battlefield or as it
  enters.
- **CR 122.6a** - "If the effect doesn't specify a player, the object's
  controller puts those counters on it."
- **CR 604.2** - a static ability's effect is active while its permanent is on
  the battlefield with the ability.
- **CR 611.3a** - "A continuous effect generated by a static ability isn't
  'locked in'; it applies at any given moment to whatever its text
  indicates."
- **CR 613.1f** - layer 6, where the keywords are granted.
- **CR 702.11a** - hexproof; **CR 702.19a** - trample.
"""

from magic_cards_model.machines import Step
from magic_cards_model.machines.combat import Keyword, has_keyword
from magic_cards_model.models.card_state import Counter
from magic_cards_model.models.game import Game
from tests.scenarios.harness import Scenario


def _board(*alice: str, bob: tuple[str, ...] = ("Grizzly Bears",)) -> Scenario:
    return (
        Scenario()
        .player("alice", battlefield=list(alice), library=["Forest"] * 6)
        .player("bob", battlefield=list(bob), library=["Forest"] * 6)
    )


def _hexproof(scenario, permanent) -> bool:
    return scenario.game.hexproof_abilities(permanent)[0]


def _resolve_pending(scenario) -> None:
    scenario.game.put_triggers_on_stack()
    while scenario.game.stack:
        scenario.resolve_top()


def _next_turn(scenario) -> None:
    active = scenario.turn.active_player
    while scenario.turn.active_player == active:
        _resolve_pending(scenario)
        scenario.advance()


# -- Beast, Erudite Aerialist -------------------------------------------------


def test_beast_flies_once_you_have_put_a_counter_on_him_this_turn():
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")
    assert not has_keyword(beast, Keyword.FLYING, scenario.game)

    scenario.game.add_counters(beast, Counter.PLUS_ONE, 1, putter="alice")

    assert has_keyword(beast, Keyword.FLYING, scenario.game)


def test_beast_keeps_flying_after_the_counter_is_gone():
    """It is a fact about this turn, not about the counter still being there:
    a -1/-1 counter annihilating the +1/+1 (CR 704.5q) does not undo that you
    put it on him."""
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")

    scenario.game.add_counters(beast, Counter.PLUS_ONE, 1, putter="alice")
    scenario.game.add_counters(beast, Counter.MINUS_ONE, 1, putter="bob")
    scenario.state_based_actions()

    assert beast.counter_count(Counter.PLUS_ONE) == 0
    assert has_keyword(beast, Keyword.FLYING, scenario.game)


def test_beast_does_not_fly_off_a_counter_an_opponent_put():
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")

    scenario.game.add_counters(beast, Counter.PLUS_ONE, 1, putter="bob")

    assert not has_keyword(beast, Keyword.FLYING, scenario.game)


def test_beast_does_not_fly_off_a_counter_on_another_creature():
    scenario = _board("Beast, Erudite Aerialist", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")
    bears = scenario.creature("Grizzly Bears", "alice")

    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")

    assert not has_keyword(beast, Keyword.FLYING, scenario.game)


def test_beast_does_not_fly_off_another_kind_of_counter():
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")

    scenario.game.add_counters(beast, "shield", 1, putter="alice")

    assert not has_keyword(beast, Keyword.FLYING, scenario.game)


def test_beast_stops_flying_on_the_next_turn():
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")
    scenario.game.add_counters(beast, Counter.PLUS_ONE, 1, putter="alice")

    _next_turn(scenario)

    assert beast.counter_count(Counter.PLUS_ONE) == 1
    assert not has_keyword(beast, Keyword.FLYING, scenario.game)


def test_the_history_survives_a_round_trip():
    """The ledger is game state: a decoded game still knows what was put on
    what this turn."""
    scenario = _board("Beast, Erudite Aerialist").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beast = scenario.creature("Beast, Erudite Aerialist", "alice")
    scenario.game.add_counters(beast, Counter.PLUS_ONE, 1, putter="alice")

    decoded = Game.model_validate(scenario.game.model_dump(mode="json"))
    (copy,) = [p for p in decoded.battlefield if p.name == beast.name]

    assert has_keyword(copy, Keyword.FLYING, decoded)


# -- Kid Loki -----------------------------------------------------------------


def test_kid_loki_gives_hexproof_to_each_creature_you_put_a_counter_on():
    scenario = _board("Kid Loki", "Grizzly Bears", "Knight of Wundagore").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    knight = scenario.creature("Knight of Wundagore", "alice")

    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")

    assert _hexproof(scenario, bears)
    assert not _hexproof(scenario, knight)


def test_kid_loki_counts_himself():
    scenario = _board("Kid Loki").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    loki = scenario.creature("Kid Loki", "alice")

    scenario.game.add_counters(loki, Counter.PLUS_ONE, 1, putter="alice")

    assert _hexproof(scenario, loki)


def test_kid_loki_ignores_a_creature_you_do_not_control():
    """ "Each creature you control" - alice's counter on bob's Bears does not
    make them hexproof."""
    scenario = _board("Kid Loki").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    theirs = scenario.creature("Grizzly Bears", "bob")

    scenario.game.add_counters(theirs, Counter.PLUS_ONE, 1, putter="alice")

    assert not _hexproof(scenario, theirs)


def test_kid_loki_ignores_counters_an_opponent_put():
    scenario = _board("Kid Loki", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")

    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="bob")

    assert not _hexproof(scenario, bears)


def test_kid_loki_protects_nothing_once_he_is_gone():
    """CR 604.2: the grant lasts only while Kid Loki is on the battlefield."""
    scenario = _board("Kid Loki", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    loki = scenario.creature("Kid Loki", "alice")
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")

    scenario.game.put_into_graveyard(loki)

    assert not _hexproof(scenario, bears)


# -- Iridescent Hornbeetle ----------------------------------------------------


def test_hornbeetle_counts_the_counters_you_put_this_turn():
    """Two counters on the Bears and one on the Hornbeetle itself - three
    counters put on creatures under alice's control, three Insects. bob's
    counter on his own creature and alice's on bob's creature do not count."""
    scenario = _board("Iridescent Hornbeetle", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    beetle = scenario.creature("Iridescent Hornbeetle", "alice")
    bears = scenario.creature("Grizzly Bears", "alice")
    theirs = scenario.creature("Grizzly Bears", "bob")

    scenario.game.add_counters(bears, Counter.PLUS_ONE, 2, putter="alice")
    scenario.game.add_counters(beetle, Counter.PLUS_ONE, 1, putter="alice")
    scenario.game.add_counters(theirs, Counter.PLUS_ONE, 1, putter="alice")
    scenario.game.add_counters(theirs, Counter.PLUS_ONE, 1, putter="bob")
    while scenario.step is not Step.END_STEP:
        _resolve_pending(scenario)
        scenario.advance()
    _resolve_pending(scenario)

    insects = [p for p in scenario.game.battlefield if p.name == "Insect Token"]
    assert len(insects) == 3


def test_hornbeetle_makes_nothing_on_a_turn_without_counters():
    scenario = _board("Iridescent Hornbeetle").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    while scenario.step is not Step.END_STEP:
        scenario.advance()
    _resolve_pending(scenario)

    assert not [p for p in scenario.game.battlefield if p.name == "Insect Token"]


# -- "Creatures you control with +1/+1 counters on them have trample" --------


def test_training_regimen_gives_trample_to_creatures_with_counters():
    scenario = _board("Training Regimen", "Grizzly Bears", "Kid Loki").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")

    assert has_keyword(bears, Keyword.TRAMPLE, scenario.game)
    loki = scenario.creature("Kid Loki", "alice")
    assert not has_keyword(loki, Keyword.TRAMPLE, scenario.game)


def test_training_regimen_ignores_an_opponents_creature_and_other_counters():
    scenario = _board("Training Regimen", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    theirs = scenario.creature("Grizzly Bears", "bob")
    scenario.game.add_counters(theirs, Counter.PLUS_ONE, 1, putter="bob")
    scenario.game.add_counters(bears, "shield", 1, putter="alice")

    assert not has_keyword(theirs, Keyword.TRAMPLE, scenario.game)
    assert not has_keyword(bears, Keyword.TRAMPLE, scenario.game)


def test_training_regimen_trample_ends_with_the_last_counter():
    """CR 611.3a: the grant is not locked in."""
    scenario = _board("Training Regimen", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")
    scenario.game.add_counters(bears, Counter.MINUS_ONE, 1, putter="alice")
    scenario.state_based_actions()

    assert not has_keyword(bears, Keyword.TRAMPLE, scenario.game)


def test_training_regimen_puts_a_counter_at_the_beginning_of_combat():
    """Its second ability, at the beginning of combat on your turn: a
    +1/+1 counter on target creature you control - which then tramples."""
    scenario = _board("Training Regimen", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    scenario.choose_trigger_targets("Training Regimen", [bears])

    scenario.advance()
    _resolve_pending(scenario)

    assert bears.counter_count(Counter.PLUS_ONE) == 1
    assert has_keyword(bears, Keyword.TRAMPLE, scenario.game)


def test_badgermole_reads_the_same_sentence():
    scenario = _board("Badgermole", "Grizzly Bears").build()
    scenario.start_at(Step.PRECOMBAT_MAIN)
    bears = scenario.creature("Grizzly Bears", "alice")
    mole = scenario.creature("Badgermole", "alice")
    scenario.game.add_counters(bears, Counter.PLUS_ONE, 1, putter="alice")

    assert has_keyword(bears, Keyword.TRAMPLE, scenario.game)
    assert not has_keyword(mole, Keyword.TRAMPLE, scenario.game)
